#[derive(Clone, Copy, PartialEq, Eq)]
enum AnonymousKey {
    /// Only ring notes, every input disclosed by its commitment.
    Commitment,
    /// A default-ring note among the spends, every input opens in full.
    Entry,
}

/// Two spends of the sender paying an inbox and a pair stream, change under a free tag.
struct AnonymousCase {
    name: &'static str,
    key: AnonymousKey,
    exits: bool,
}

impl AnonymousCase {
    fn case(self) -> Case {
        let entry = self.key == AnonymousKey::Entry;
        let mut transfer = Transfer::fixture();
        transfer.nullifiers.push(field(0x1e));
        let sender_nullifier_pk = field(0x5a);
        let sender = |asset_address, amount| Note {
            owner_key: SENDER_KEY,
            nullifier_pk: sender_nullifier_pk,
            asset_address,
            amount,
            ..Note::default()
        };
        let inbox_u = x25519_u(0x50);
        let inbox_key = InboxKey::derive(&transfer.ring_id(), &tagged_x25519(&inbox_u)).unwrap();
        let first_contact = field(0x71);
        let pair_key = PairKey::derive(&SlotSecret::new(first_contact).unwrap()).unwrap();
        let change_field = field(0x5c);
        let change = Output::Ring {
            note: sender(MINT, 500),
            recipient_u: x25519_u(0x52),
            tag: Some(RingTag::from_field(&change_field).unwrap()),
        };
        let change_stream = json!({"stream": "change", "tag_field": hex(change_field)});
        let mut paid = vec![
            (
                Output::Ring {
                    note: ring_note(0xb5, SOL, 4000),
                    recipient_u: inbox_u,
                    tag: Some(inbox_key.tag(EPOCH, TagIndex::new(0).unwrap()).unwrap()),
                },
                json!({"stream": "inbox", "inbox_key": hex(inbox_key.as_bytes()), "index": 0}),
            ),
            (
                Output::Ring {
                    note: ring_note(0xb6, MINT, 2500),
                    recipient_u: x25519_u(0x51),
                    tag: Some(pair_key.tag(EPOCH, TagIndex::new(3).unwrap()).unwrap()),
                },
                json!({"stream": "pair", "first_contact_secret": hex(first_contact), "pair_key": hex(pair_key.as_bytes()), "index": 3}),
            ),
        ];
        paid.extend(match self.exits {
            true => [
                (Output::Exit(ring_note(0xe7, SOL, 1000)), Value::Null),
                (change, change_stream),
            ],
            false => [(change, change_stream), (Output::Dummy, Value::Null)],
        });
        let (outputs, streams): (Vec<Output>, Vec<Value>) = paid.into_iter().unzip();
        let slots = transfer.slots(Rail::Anonymous, &outputs);
        let spent = [
            (sender(SOL, 5000), field(0x60), Some(transfer.ring)),
            (
                sender(MINT, 3000),
                field(0x61),
                (!entry).then_some(transfer.ring),
            ),
        ];
        let commitments: Vec<[u8; 32]> = spent
            .iter()
            .map(|(note, blinding, ring)| {
                note.commitment(Placement {
                    blinding: *blinding,
                    ring: *ring,
                    tree_id: transfer.tree_id,
                })
            })
            .collect();
        let inputs = match self.key {
            AnonymousKey::Entry => AnonymousInputs::Openings {
                sender_nullifier_pk,
                inputs: spent
                    .iter()
                    .map(|(note, blinding, _)| Some(input_opening(note, *blinding)))
                    .collect(),
            },
            AnonymousKey::Commitment => {
                AnonymousInputs::Commitments(commitments.iter().copied().map(Some).collect())
            }
        };
        let disclosure = transfer.anonymous_disclosure(SENDER_KEY, &outputs, inputs);
        let AuditDisclosure::Anonymous(anonymous) = &disclosure else {
            unreachable!("an anonymous transfer takes the anonymous layout");
        };
        let class = anonymous.layout.key.class();
        let transaction = transfer.publish(Publish {
            slots: slots.iter().map(|slot| slot.output.clone()).collect(),
            disclosure: &disclosure,
            auditor: &auditor().pubkey(),
        });
        let layout = disclosure.layout();
        let frame = transfer.frame(Frame {
            tx: &transaction,
            layout,
            data_free: data_free(&outputs),
        });
        let mut json = Map::new();
        json.insert("name".into(), self.name.into());
        json.insert(
            "layout".into(),
            layout_value(&frame, RingRail::Anonymous).into(),
        );
        json.extend(transfer_json(&transfer));
        json.insert("epoch".into(), EPOCH.into());
        json.insert("sender_key".into(), hex(SENDER_KEY).into());
        json.insert(
            "sender_nullifier_pk".into(),
            hex(sender_nullifier_pk).into(),
        );
        json.insert(
            "key".into(),
            match self.key {
                AnonymousKey::Entry => "entry",
                AnonymousKey::Commitment => "commitment",
            }
            .into(),
        );
        json.insert("class".into(), class.into());
        json.insert(
            "inputs".into(),
            spent
                .iter()
                .zip(&transfer.nullifiers)
                .zip(&commitments)
                .map(|(((note, blinding, ring), nullifier), commitment)| {
                    json!({
                        "nullifier": hex(nullifier),
                        "asset_address": hex(note.asset_address.as_array()),
                        "asset": hex(note.asset()),
                        "amount": note.amount,
                        "blinding": hex(blinding),
                        "input_tree_id": transfer.tree_id,
                        "ring": if ring.is_some() { "ring" } else { "default" },
                        "owner_hash": hex(note.owner_hash()),
                        "commitment": hex(commitment),
                    })
                })
                .collect(),
        );
        json.insert(
            "slots".into(),
            outputs
                .iter()
                .zip(&slots)
                .zip(streams)
                .map(|((output, slot), stream)| {
                    let mut map = slot_json(output, slot);
                    if let Value::Object(stream) = stream {
                        map.extend(stream);
                    }
                    Value::Object(map)
                })
                .collect(),
        );
        json.extend(disclosure_json(&transfer, &disclosure));
        let known = spent
            .iter()
            .zip(&commitments)
            .map(|(spend, commitment)| (*commitment, known_note(spend)))
            .collect();
        let inputs = spent
            .iter()
            .zip(&transfer.nullifiers)
            .zip(&commitments)
            .map(|(((note, blinding, ring), nullifier), commitment)| {
                let commitment = *commitment;
                AuditedInput {
                    nullifier: *nullifier,
                    opening: Some(AuditedInputOpening {
                        asset: note.asset(),
                        mint: Some(note.asset_address),
                        amount: note.amount,
                        blinding: *blinding,
                        ring: Some(match ring {
                            Some(_) => InputRing::Ring { commitment },
                            None => InputRing::Default { commitment },
                        }),
                    }),
                }
            })
            .collect();
        Case {
            json: Value::Object(json),
            audit: Audit {
                transaction,
                frame,
                mode: RingMode::Anonymous,
                layout,
                outputs: audited_outputs(&outputs, &slots),
                input_trees: vec![Some(transfer.tree_id); 2],
                known,
                escrowed: HashMap::new(),
                inputs,
            },
        }
    }
}

