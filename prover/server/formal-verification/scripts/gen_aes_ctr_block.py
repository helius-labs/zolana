"""Generate VerifiableEncryption/Aes/CtrBlock.lean.

Usage, from prover/server/formal-verification:

    python3 scripts/gen_aes_ctr_block.py VerifiableEncryption/Aes/CtrBlock.lean

The proof walks the extracted AesCtrBlock_32_12_16_16 gadget by gadget: key
expansion, the nonce lookups and the initial AddRoundKey, the plaintext
lookups, round 1 (three full columns and the cached column 0 with counter 2),
rounds 2 to 13 four columns at a time, the final round, and the ciphertext
equalities. The layout it walks is the one in VerifiableEncryption/Circuit/Top.lean;
rerun this script and rebuild after a re-extraction.
"""
import sys

out_path = sys.argv[1]

W = "(keyExpansion256 (keyBytes Key))"
BLK = "(counterBlock (bytesOf Nonce) 2)"


def T(r):
    return f"(roundsFrom {W} {BLK} {r})"


def RK(r):
    return f"(fun i : Fin 16 => rkByte {W} ⟨16 * {r} + i.val, by omega⟩)"


def column_source(c, r):
    return 4 * ((c + r) % 4) + r


lines = []
emit = lines.append

emit("-- Code generated by scripts/gen_aes_ctr_block.py. DO NOT EDIT.")
emit("")
emit("import VerifiableEncryption.Aes.CtrSpec")
emit("import VerifiableEncryption.Circuit.Top")
emit("")
emit("/-!")
emit("The extracted `AesCtrBlock_32_12_16_16` encrypts one block with AES-256 at counter 2.")
emit("-/")
emit("")
emit("namespace ZolanaVE.Aes")
emit("")
emit("open ZolanaVE")
emit("")
emit("variable [Fact (Nat.Prime Order)]")
emit("")
emit("set_option maxHeartbeats 0 in")
emit("theorem aesCtrBlock_cps (hL : AesLookupSem) {Key : List.Vector F 32} {Nonce : List.Vector F 12}")
emit("    {Plaintext Ciphertext : List.Vector F 16}")
emit("    (h : AesCtrBlock_32_12_16_16 Key Nonce Plaintext Ciphertext) :")
emit("    (∀ n, Key.get n = ((keyBytes Key n).toNat : F)) ∧")
emit("    (∀ n, Nonce.get n = ((bytesOf Nonce n).toNat : F)) ∧")
emit("    (∀ n, Plaintext.get n = ((bytesOf Plaintext n).toNat : F)) ∧")
emit("    ∀ i, Ciphertext.get i =")
emit("      ((encryptBlock (keyBytes Key) (counterBlock (bytesOf Nonce) 2) i ^^^ bytesOf Plaintext i).toNat : F) := by")
emit("  unfold AesCtrBlock_32_12_16_16 at h")
emit("  replace h := keyExpansion_cps hL h")
emit("  obtain ⟨hk, h⟩ := h")
emit("  simp only [vec2_get0, vec2_get1, List.Vector.get_ofFn] at h")
for n in range(12):
    emit("  replace h := keyByte_step hL h")
    emit(f"  obtain ⟨hn{n}, h⟩ := h")
for _ in range(12):
    emit("  replace h := let_step h")
for g in range(3):
    emit(f"  replace h := nonceWord_cps hL {W} (bytesOf Nonce) {g} (by norm_num) rfl rfl rfl rfl h")
for n in range(16):
    emit("  replace h := keyByte_step hL h")
    emit(f"  obtain ⟨hp{n}, h⟩ := h")


def state0_entry_proof(c, r):
    si = column_source(c, r)
    if si < 12:
        return "rfl"
    return f"(by rw [show columnSource {c} {r} = ⟨{si}, by norm_num⟩ from rfl, state0_{si}] <;> rfl)"


for c in (1, 2, 3):
    es = " ".join(state0_entry_proof(c, r) for r in range(4))
    emit(f"  replace h := roundColumnLit_cps hL {T(0)} {RK(1)} {T(1)} (rounds_step _ _ 0 (by norm_num)) {c}")
    emit(f"    {es} rfl rfl rfl rfl h")
emit(f"  replace h := cachedColumn_cps hL {T(0)} {RK(1)} {T(1)} (rounds_step _ _ 0 (by norm_num))")
emit(f"    (rkByte {W} 15) (state0_15 _ _) rfl rfl rfl rfl rfl rfl rfl rfl h")
for r in range(2, 14):
    emit(f"  replace h := round4_cps hL {T(r - 1)} {RK(r)} {T(r)} (rounds_step _ _ {r - 1} (by norm_num))")
    emit("    " + " ".join(["rfl"] * 16) + " h")
emit(f"  replace h := finalRound_cps hL {T(13)} {RK(14)} (bytesOf Plaintext)")
emit("    (by intro i; fin_cases i <;> rfl) (by intro i; fin_cases i <;> rfl)")
emit("    (by intro i; fin_cases i <;> rfl) h")
emit("  simp only [gate_eq] at h")
emit("  obtain ⟨" + ", ".join(f"e{n}" for n in range(16)) + ", -⟩ := h")
emit("  refine ⟨hk, ?_, ?_, ?_⟩")
emit("  · intro n")
emit("    fin_cases n")
for n in range(12):
    emit(f"    · exact hn{n}")
emit("  · intro n")
emit("    fin_cases n")
for n in range(16):
    emit(f"    · exact hp{n}")
emit("  · intro i")
emit("    rw [encryptBlock_byte]")
emit("    fin_cases i")
for n in range(16):
    emit(f"    · exact e{n}.symm")
emit("")
emit("end ZolanaVE.Aes")
emit("")

with open(out_path, "w") as f:
    f.write("\n".join(lines))
