"""Generate VerifiableEncryption/Aes/KeyExpansion.lean.

Usage, from prover/server/formal-verification:

    python3 scripts/gen_aes_key_expansion.py VerifiableEncryption/Aes/KeyExpansion.lean

The proof walks the extracted AesKeyExpansion_32 word by word. Each extracted
part AesKeyExpansion_32_pN is unfolded only when the walk reaches the first word
whose decode lies in that part, which keeps the hypothesis small; the part
boundaries are read from VerifiableEncryption/Circuit/Aes.lean, so rerun this
script after a re-extraction. Optional arguments `<last word + 1> nofinish`
emit a truncated proof ending in `sorry`, for debugging only.
"""
import os
import re
import sys

out_path = sys.argv[1]
upto = int(sys.argv[2]) if len(sys.argv) > 2 else 60
finish = upto == 60 and (len(sys.argv) <= 3)

circuit_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                            "VerifiableEncryption", "Circuit", "Aes.lean")
with open(circuit_path) as f:
    circuit_src = f.read()
bodies = {}
for definition in re.split(r"\n(?=def )", circuit_src):
    m = re.match(r"def (AesKeyExpansion_32(?:_p\d+)?) ", definition)
    if m:
        bodies[m.group(1)] = definition
part_count = len(bodies) - 1
parts = {}
decodes = 0
for index in range(part_count + 1):
    name = "AesKeyExpansion_32" if index == 0 else f"AesKeyExpansion_32_p{index}"
    if index > 0:
        parts[8 + decodes] = index
    decodes += len(re.findall(r"AesDecodeWord_4 ", bodies[name]))
if decodes != 52:
    raise SystemExit(f"expected 52 key words, found {decodes}")

W = "keyExpansion256 (keyBytes Key)"


def w(i):
    return f"({W} ⟨{i}, by norm_num⟩)"


rcon_bytes = {1: 0x01, 2: 0x02, 3: 0x04, 4: 0x08, 5: 0x10, 6: 0x20, 7: 0x40}

lines = []
emit = lines.append

emit("-- Code generated by scripts/gen_aes_key_expansion.py. DO NOT EDIT.")
emit("")
emit("import VerifiableEncryption.Aes.KeySteps")
emit("")
emit("/-!")
emit("The extracted `AesKeyExpansion_32` computes FIPS-197 `keyExpansion256` of its key bytes.")
emit("-/")
emit("")
emit("namespace ZolanaVE.Aes")
emit("")
emit("open ZolanaVE")
emit("")
for n, r in rcon_bytes.items():
    emit(f"theorem rcon_{n} : rcon {n} = ![{r}#8, 0, 0, 0] := by")
    emit("  funext j")
    emit("  fin_cases j <;> decide")
    emit("")
emit("variable [Fact (Nat.Prime Order)]")
emit("")
emit("def keyBytes (Key : List.Vector F 32) : Fin 32 → Byte := fun n => BitVec.ofNat 8 (Key.get n).val")
emit("")
emit("def rkByte (w : Fin 60 → Word) (n : Fin 240) : Byte := w ⟨n.val / 4, by omega⟩ ⟨n.val % 4, by omega⟩")
emit("")
def wrap(entries):
    rows = [", ".join(entries[i:i + 4]) for i in range(0, len(entries), 4)]
    return "\n  " + ",\n  ".join(rows)


spread_entries = wrap([f"(spread8 (w ⟨{n // 4}, by norm_num⟩ {n % 4}) : F)" for n in range(240)])
byte_entries = wrap([f"((w ⟨{n // 4}, by norm_num⟩ {n % 4}).toNat : F)" for n in range(240)])
emit("/-- The spread round-key bytes in the literal order the extracted gadget returns them. -/")
emit(f"def rkSpreadVec (w : Fin 60 → Word) : List.Vector F 240 := vec![{spread_entries}]")
emit("")
emit(f"def rkByteVec (w : Fin 60 → Word) : List.Vector F 240 := vec![{byte_entries}]")
emit("")
emit("theorem rkSpreadVec_eq (w : Fin 60 → Word) :")
emit("    rkSpreadVec w = List.Vector.ofFn fun n => (spread8 (rkByte w n) : F) := rfl")
emit("")
emit("theorem rkByteVec_eq (w : Fin 60 → Word) :")
emit("    rkByteVec w = List.Vector.ofFn fun n => ((rkByte w n).toNat : F) := rfl")
emit("")
emit("set_option maxHeartbeats 0 in")
emit("theorem keyExpansion_cps (hL : AesLookupSem) {Key : List.Vector F 32}")
emit("    {k : List.Vector (List.Vector F 240) 2 → Prop} (h : AesKeyExpansion_32 Key k) :")
emit("    (∀ n, Key.get n = ((keyBytes Key n).toNat : F)) ∧")
emit(f"      k vec![List.Vector.ofFn fun n => (spread8 (rkByte ({W}) n) : F),")
emit(f"        List.Vector.ofFn fun n => ((rkByte ({W}) n).toNat : F)] := by")
emit("  unfold AesKeyExpansion_32 at h")
for n in range(32):
    emit("  replace h := keyByte_step hL h")
    emit(f"  obtain ⟨hk{n}, h⟩ := h")


def earlier_proof(i, j):
    if i - 8 < 8:
        return f"(by rw [keyExpansion256_lt8 _ {i-8} (by norm_num)]; rfl)"
    return "(by rfl)"


def prev_byte_proof(i, j):
    if i - 1 < 8:
        n = 4 * (i - 1) + j
        return f"(by rw [keyExpansion256_lt8 _ {i-1} (by norm_num)]; exact hk{n})"
    return "(by simp [wordVec])"


for i in range(8, upto):
    kind = "rot" if i % 8 == 0 else ("sub" if i % 8 == 4 else "copy")
    if i in parts:
        emit(f"  unfold AesKeyExpansion_32_p{parts[i]} at h")
    if kind == "rot":
        for j in [1, 2, 3, 0]:
            emit(f"  replace h := sboxLet_step hL ({w(i-1)} {j}) {prev_byte_proof(i, j)} h")
        emit("  replace h := let_step h")
        rn = i // 8
        spread_r = 6 ** (rn - 1)
        A = w(i - 8)
        B = f"(fun j => sb ({w(i-1)} (j + 1)))"
        C = f"![{rcon_bytes[rn]}#8, 0, 0, 0]"
        hx = " ".join(earlier_proof(i, j) for j in range(4))
        hy0 = f"(by rw [gate_add]; simp [show spread8 {rcon_bytes[rn]}#8 = {spread_r} by decide] <;> rfl)"
        hys = " ".join("(by simp [spread8_zero', spread8_zero] <;> rfl)" for _ in range(3))
        hR = (f"(fun j => by rw [keyWord_rot _ {i} (by norm_num) (by norm_num) (by norm_num) j, rcon_{rn}]; "
              f"fin_cases j <;> simp [BitVec.xor_assoc] <;> rfl)")
    elif kind == "sub":
        for j in range(4):
            emit(f"  replace h := sboxLet_step hL ({w(i-1)} {j}) {prev_byte_proof(i, j)} h")
        A = w(i - 8)
        B = f"(fun j => sb ({w(i-1)} j))"
        C = "(fun _ => 0)"
        hx = " ".join(earlier_proof(i, j) for j in range(4))
        hy0 = "(by simp [spread8_zero', spread8_zero])"
        hys = " ".join("(by simp [spread8_zero', spread8_zero])" for _ in range(3))
        hR = (f"(fun j => by rw [keyWord_sub _ {i} (by norm_num) (by norm_num) (by norm_num) j]; "
              f"simp <;> rfl)")
    else:
        A = w(i - 8)
        B = w(i - 1)
        C = "(fun _ => 0)"
        hx = " ".join(earlier_proof(i, j) for j in range(4))
        hy0 = "(by simp [spread8_zero', spread8_zero])"
        hys = " ".join("(by simp [spread8_zero', spread8_zero])" for _ in range(3))
        hR = (f"(fun j => by rw [keyWord_copy _ {i} (by norm_num) (by norm_num) (by norm_num) (by norm_num) j]; "
              f"simp <;> rfl)")
    emit(f"  replace h := keyWord_cps hL {A} {B} {C} {w(i)}")
    emit(f"    {hx}")
    emit(f"    {hy0} {hys}")
    emit(f"    {hR} h")

if finish:
    emit("  have hk : ∀ n, Key.get n = ((keyBytes Key n).toNat : F) := by")
    emit("    clear h")
    emit("    intro n")
    emit("    fin_cases n <;> assumption")
    for n in range(32):
        emit(f"  have hs{n} : (spread8 (BitVec.ofNat 8 (Key.get ({n} : Fin 32)).val) : F) =")
        emit(f"      (spread8 ({W} ⟨{n // 4}, by norm_num⟩ {n % 4}) : F) := by")
        emit(f"    rw [keyExpansion256_lt8 _ {n // 4} (by norm_num)]; rfl")
    for n in range(32):
        emit(f"  have hb{n} : Key.get ({n} : Fin 32) = (({W} ⟨{n // 4}, by norm_num⟩ {n % 4}).toNat : F) := by")
        emit(f"    rw [keyExpansion256_lt8 _ {n // 4} (by norm_num)]; exact hk{n}")
    emit("  rw [" + ", ".join(f"hs{n}" for n in range(32)) + "] at h")
    emit("  rw [" + ", ".join(f"hb{n}" for n in range(32)) + "] at h")
    emit("  refine ⟨hk, ?_⟩")
    emit("  rw [← rkSpreadVec_eq, ← rkByteVec_eq]")
    emit("  exact h")
else:
    emit("  sorry")
emit("")
emit("end ZolanaVE.Aes")
emit("")

with open(out_path, "w") as f:
    f.write("\n".join(lines))
