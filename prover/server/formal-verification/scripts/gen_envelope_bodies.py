#!/usr/bin/env python3
"""Generate VerifiableEncryption/Envelope/Bodies.lean.

Both extracted envelopes start with the key-agreement constraints of
`AgreeKey_32_65_6` verbatim and differ only in what follows the packed points.
This script cuts the extracted text into

* `AgreeKeyBody sk pk Q`: the shared key-agreement constraints, ending in the
  continuation `Q gate_259 gate_263 gate_364 gate_366 gate_380` (recipient
  packing, ephemeral packing, shared-x split and its high part),
* `Envelope16Tail` / `EnvelopeMergeKdf`: the remaining lines of each
  envelope's first part, verbatim,

and checks that the shared prefix is identical in all three circuits, so the
bridge lemmas hold by unfolding. Any difference aborts generation.

Usage (from prover/server/formal-verification):
  scripts/gen_envelope_bodies.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "VerifiableEncryption/Circuit/Top.lean"
OUT = ROOT / "VerifiableEncryption/Envelope/Bodies.lean"

AGREE_TAIL = [
    "Gates.eq gate_259 (Packed.get (0 : Fin 6)) ∧",
    "Gates.eq gate_263 (Packed.get (1 : Fin 6)) ∧",
    "Gates.eq (gate_364.get (0 : Fin 2)) (Packed.get (2 : Fin 6)) ∧",
    "Gates.eq (gate_364.get (1 : Fin 2)) (Packed.get (3 : Fin 6)) ∧",
    "Gates.eq gate_380 (Packed.get (4 : Fin 6)) ∧",
    "Gates.eq (gate_366.get (1 : Fin 2)) (Packed.get (5 : Fin 6)) ∧",
    "True",
]


def bodies(text):
    defs, name = {}, None
    for line in text.split("\n"):
        m = re.match(r"^def (\S+) ", line)
        if m:
            name = m.group(1)
            defs[name] = []
        elif line.startswith("end "):
            name = None
        elif name is not None and line.strip():
            defs[name].append(line.rstrip())
    return defs


def check(cond, msg):
    if not cond:
        sys.exit(f"gen_envelope_bodies: {msg}")


def main():
    defs = bodies(SRC.read_text())
    ak, ak1 = defs["AgreeKey_32_65_6"], defs["AgreeKey_32_65_6_p1"]
    check([l.strip() for l in ak1[-7:]] == AGREE_TAIL, "AgreeKey_32_65_6_p1 tail changed")
    check(ak[-1].strip().startswith("AgreeKey_32_65_6_p1 "), "AgreeKey_32_65_6 does not end in its part")
    prefix_main, prefix_p1 = ak[:-1], ak1[:-7]
    tails = {}
    for env, p1 in (("Envelope_32_65_16_16", "Envelope_32_65_16_16_p1"),
                    ("EnvelopeMerge_32_65_40_4", "EnvelopeMerge_32_65_40_4_p1")):
        main_body, p1_body = defs[env], defs[p1]
        check(main_body[:-1] == prefix_main, f"{env} key agreement differs from AgreeKey_32_65_6")
        check(main_body[-1].strip().startswith(p1 + " "), f"{env} does not end in {p1}")
        check(p1_body[:len(prefix_p1)] == prefix_p1, f"{p1} key agreement differs from AgreeKey_32_65_6_p1")
        tails[env] = p1_body[len(prefix_p1):]
    heads = {}
    for env, t in tails.items():
        check(re.match(r"^    Poseidon_[78] vec!\[.*\] \(0:F\) fun gate_381 =>$", t[0]) is not None,
              f"{env} tail does not open with the shared-secret Poseidon")
        check(t[-1].strip().split()[-4:] == ["gate_396", "gate_397", "gate_398", "gate_399"],
              f"{env} tail does not end in its second part")
        heads[env] = t[1:-1]
    check(heads["Envelope_32_65_16_16"] == heads["EnvelopeMerge_32_65_40_4"], "the KDF segments differ")
    head = "\n".join(heads["Envelope_32_65_16_16"])
    hyp = {env: t[0].replace("fun gate_381 =>", "fun gate_381 => KdfAesHead gate_381 fun gate_396 gate_397 gate_398 gate_399 =>\n  " + t[-1].strip() + ")")
           .replace("    Poseidon_", "    (Poseidon_", 1)
           for env, t in tails.items()}
    body = "\n".join(prefix_main + prefix_p1)
    out = f"""-- Code generated by scripts/gen_envelope_bodies.py. DO NOT EDIT.

import VerifiableEncryption.Circuit.Top

/-!
The key-agreement constraints shared verbatim by `AgreeKey_32_65_6` and both
extracted envelopes, with the continuation abstracted, and the remaining
first-part constraints of each envelope.
-/

set_option linter.unusedVariables false

namespace ZolanaVE

variable [Fact (Nat.Prime Order)]

def AgreeKeyBody (EphemeralSk : List.Vector F 32) (RecipientPk : List.Vector F 65)
    (Q : F → F → List.Vector F 2 → List.Vector F 2 → F → Prop) : Prop :=
{body}
    Q gate_259 gate_263 gate_364 gate_366 gate_380

def Envelope16Tail (EphemeralSk : List.Vector F 32) (RecipientPk : List.Vector F 65)
    (Plaintext : List.Vector F 16) (RecipientLo RecipientHi EphemeralLo EphemeralHi : F)
    (Ciphertext : List.Vector F 16) (gate_259 gate_263 : F) (gate_364 gate_366 : List.Vector F 2)
    (gate_380 : F) : Prop :=
{chr(10).join(tails["Envelope_32_65_16_16"])}

def EnvelopeMergeKdf (EphemeralSk : List.Vector F 32) (RecipientPk : List.Vector F 65)
    (Plaintext : List.Vector F 40) (Context : F) (Elements : List.Vector F 4) (Blinding : F)
    (gate_259 gate_263 : F) (gate_364 gate_366 : List.Vector F 2) (gate_380 : F) : Prop :=
{chr(10).join(tails["EnvelopeMerge_32_65_40_4"])}

/-- The KDF and the AES key expansion head shared by both envelopes after the
shared-secret Poseidon; `P` receives the nonce bytes, the expanded key and the
two spread nonce bytes. -/
def KdfAesHead (gate_381 : F)
    (P : List.Vector F 32 → List.Vector (List.Vector F 240) 2 → F → F → Prop) : Prop :=
{head}
    P gate_396 gate_397 gate_398 gate_399

theorem envelope16Tail_head {{EphemeralSk : List.Vector F 32}} {{RecipientPk : List.Vector F 65}}
    {{Plaintext Ciphertext : List.Vector F 16}} {{RecipientLo RecipientHi EphemeralLo EphemeralHi : F}}
    {{gate_259 gate_263 gate_380 : F}} {{gate_364 gate_366 : List.Vector F 2}}
    (h : Envelope16Tail EphemeralSk RecipientPk Plaintext RecipientLo RecipientHi EphemeralLo EphemeralHi
      Ciphertext gate_259 gate_263 gate_364 gate_366 gate_380) :
{hyp["Envelope_32_65_16_16"]} := h

theorem envelopeMergeKdf_head {{EphemeralSk : List.Vector F 32}} {{RecipientPk : List.Vector F 65}}
    {{Plaintext : List.Vector F 40}} {{Context Blinding : F}} {{Elements : List.Vector F 4}}
    {{gate_259 gate_263 gate_380 : F}} {{gate_364 gate_366 : List.Vector F 2}}
    (h : EnvelopeMergeKdf EphemeralSk RecipientPk Plaintext Context Elements Blinding
      gate_259 gate_263 gate_364 gate_366 gate_380) :
{hyp["EnvelopeMerge_32_65_40_4"]} := h

theorem envelope16_body {{Esk : List.Vector F 32}} {{Rpk : List.Vector F 65}} {{Pt Ct : List.Vector F 16}}
    {{RLo RHi ELo EHi : F}} (h : Envelope_32_65_16_16 Esk Rpk Pt RLo RHi ELo EHi Ct) :
    AgreeKeyBody Esk Rpk (Envelope16Tail Esk Rpk Pt RLo RHi ELo EHi Ct) := h

theorem envelopeMerge_body {{Esk : List.Vector F 32}} {{Rpk : List.Vector F 65}} {{Pt : List.Vector F 40}}
    {{Ctx Bl : F}} {{El : List.Vector F 4}} (h : EnvelopeMerge_32_65_40_4 Esk Rpk Pt Ctx El Bl) :
    AgreeKeyBody Esk Rpk (EnvelopeMergeKdf Esk Rpk Pt Ctx El Bl) := h

end ZolanaVE
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out)


if __name__ == "__main__":
    main()
