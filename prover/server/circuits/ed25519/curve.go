// Package ed25519 verifies standard Ed25519 signatures on BN254, including
// SHA-512, with Agave precompile's ed25519-dalek 1.0.1 verify_strict semantics.
package ed25519

import (
	"errors"
	"math/big"

	"github.com/consensys/gnark-crypto/ecc"
	"github.com/consensys/gnark/constraint/solver"
	"github.com/consensys/gnark/frontend"

	"zolana/prover/circuits/verifiable-encryption/p256/emcurve/emfield"
)

func pow2(n int) *big.Int { return new(big.Int).Lsh(big.NewInt(1), uint(n)) }

// Prime returns the Edwards25519 coordinate-field modulus.
func Prime() *big.Int { return new(big.Int).Sub(pow2(255), big.NewInt(19)) }

// Order returns the order of the prime subgroup generated by the basepoint.
func Order() *big.Int {
	n, _ := new(big.Int).SetString("27742317777372353535851937790883648493", 10)
	return n.Add(n, pow2(252))
}
func parameterD() *big.Int {
	p := Prime()
	d := new(big.Int).ModInverse(big.NewInt(121666), p)
	return d.Mul(d, big.NewInt(-121665)).Mod(d, p)
}

var (
	layout = emfield.Layout{NbLimbs: 6, LimbBits: 43, PieceBits: 11}
	config = emfield.Config{Layout: layout, Arithmetic: emfield.ArithmeticV2}
)

type point struct{ x, y, t *emfield.Element }
type curve struct {
	api    frontend.API
	fp, fr *emfield.Field
	one, d *emfield.Element
}

func newCurve(api frontend.API) *curve {
	if api.Compiler().Field().Cmp(ecc.BN254.ScalarField()) != 0 {
		panic("ed25519: BN254 native field required")
	}
	fp := emfield.NewFor(api, Prime(), config)
	return &curve{api: api, fp: fp, fr: emfield.NewFor(api, Order(), config), one: fp.Const(big.NewInt(1)), d: fp.Const(parameterD())}
}
func (c *curve) identity() *point { return &point{x: c.fp.Const(new(big.Int)), y: c.one} }
func (c *curve) withT(p *point) *point {
	if p.t == nil {
		p.t = c.fp.EvalProjected(emfield.T(1, c.d, p.x, p.y))
	}
	return p
}

// The xy product is reduced before squaring; this keeps the coefficient bounds
// smaller than a lazy degree-four expansion and reuses the CRT square gadget.
func (c *curve) assertOnCurve(p *point) {
	xy := c.fp.EvalProjected(emfield.T(1, p.x, p.y))
	square := c.fp.Lazy(emfield.T(1, xy, xy))
	c.fp.AssertZeroProjected(emfield.T(1, p.y, p.y), emfield.T(-1, p.x, p.x), emfield.T(-1, c.one), emfield.T(-1, c.d, square))
}

// Twisted Edwards addition is complete: a=-1 is a square and d is a
// nonsquare in Fp. Both denominators are nonzero for all on-curve inputs.
// The bilinear products remain lazy; only output coordinates are reduced.
func (c *curve) add(p, q *point) *point {
	fp := c.fp
	c.withT(q)
	out := fp.Hint(addHint, 2, nil, p.x, p.y, q.x, q.y)
	r := &point{x: out[0], y: out[1]}
	c.assertAdd(p, q, r)
	return r
}

// assertAdd binds an already available output using the complete Edwards law.
func (c *curve) assertAdd(p, q, r *point) {
	fp := c.fp
	c.withT(q)
	// For a=-1, delta-beta-gamma equals x1*x2+y1*y2.
	beta := fp.Lazy(emfield.T(1, p.x, q.y))
	gamma := fp.Lazy(emfield.T(1, p.y, q.x))
	delta := fp.Lazy(emfield.T(1, fp.Add(p.x, p.y), fp.Add(q.x, q.y)))
	denominator := fp.Lazy(emfield.T(1, q.t, p.x, p.y))
	fp.AssertZeroProjected(emfield.T(1, r.x), emfield.T(1, r.x, denominator), emfield.T(-1, beta), emfield.T(-1, gamma))
	fp.AssertZeroProjected(emfield.T(1, r.y), emfield.T(-1, r.y, denominator), emfield.T(-1, delta), emfield.T(1, beta), emfield.T(1, gamma))
}

func (c *curve) double(p *point) *point {
	fp := c.fp
	out := fp.Hint(doubleHint, 2, nil, p.x, p.y)
	r := &point{x: out[0], y: out[1]}
	difference := fp.Lazy(emfield.T(1, p.y, p.y), emfield.T(-1, p.x, p.x))
	sum := fp.Lazy(emfield.T(1, p.y, p.y), emfield.T(1, p.x, p.x))
	fp.AssertZeroProjected(emfield.T(1, r.x, difference), emfield.T(-2, p.x, p.y))
	fp.AssertZeroProjected(emfield.T(2, r.y), emfield.T(-1, r.y, difference), emfield.T(-1, sum))
	return r
}

func (c *curve) fromBits(f *emfield.Field, bits []frontend.Variable) *emfield.Element {
	limbs := make([]frontend.Variable, 0, (len(bits)+layout.LimbBits-1)/layout.LimbBits)
	widths := make([]int, 0, cap(limbs))
	for i := 0; i < len(bits); i += layout.LimbBits {
		chunk := bits[i:min(i+layout.LimbBits, len(bits))]
		limbs = append(limbs, c.api.FromBinary(chunk...))
		widths = append(widths, len(chunk))
	}
	return f.Bounded(limbs, widths)
}
func (c *curve) decodeEncoding(encoded [32]frontend.Variable) *point {
	raw, err := c.api.Compiler().NewHint(lowSplitHint, 2, encoded[31], 7)
	if err != nil {
		panic(err)
	}
	sign := raw[1]
	c.api.AssertIsBoolean(sign)
	c.api.AssertIsEqual(encoded[31], c.api.Add(raw[0], c.api.Mul(sign, 128)))
	bytes := append([]frontend.Variable{}, encoded[:]...)
	bytes[31] = raw[0]
	y := c.byteElement(c.fp, bytes, 255)
	x := c.fp.Hint(decompressHint, 1, []frontend.Variable{sign}, y)[0]
	c.fp.AssertCanonical(x)
	// The low limb and its halved remainder are bounded, so this fixes parity
	// over the integers. No square-root hint result is trusted.
	inv2 := new(big.Int).ModInverse(big.NewInt(2), c.api.Compiler().Field())
	c.fp.RangeChecker().Check(c.api.Mul(c.api.Sub(x.Limbs()[0], sign), inv2), layout.LimbBits-1)
	p := &point{x: x, y: y}
	return p
}

func init() { solver.RegisterHint(decompressHint, addHint, doubleHint) }
func decompressHint(q *big.Int, in, out []*big.Int) error {
	return emfield.Unwrap(q, in, out, func(p *big.Int, natives, values, outputs []*big.Int) error {
		if len(natives) != 1 || len(values) != 1 || len(outputs) != 1 {
			return errors.New("ed25519 decompression shape")
		}
		y2 := new(big.Int).Mul(values[0], values[0])
		y2.Mod(y2, p)
		num := new(big.Int).Sub(y2, big.NewInt(1))
		den := new(big.Int).Mul(parameterD(), y2)
		den.Add(den, big.NewInt(1)).Mod(den, p)
		if den.ModInverse(den, p) == nil {
			return nil
		}
		x := new(big.Int).ModSqrt(num.Mul(num, den).Mod(num, p), p)
		if x == nil {
			return nil
		}
		if x.Bit(0) != natives[0].Bit(0) {
			x.Sub(p, x)
		}
		outputs[0].Set(x)
		return nil
	})
}

type hostPoint struct{ x, y *big.Int }

// Host arithmetic only reads this constant, including from concurrent hints.
var hostD = parameterD()

func hostAdd(p, q hostPoint) hostPoint {
	mod, d := Prime(), hostD
	product := new(big.Int).Mul(p.x, q.x)
	product.Mul(product, p.y).Mul(product, q.y).Mul(product, d).Mod(product, mod)
	nx := new(big.Int).Mul(p.x, q.y)
	nx.Add(nx, new(big.Int).Mul(p.y, q.x))
	ny := new(big.Int).Mul(p.y, q.y)
	ny.Add(ny, new(big.Int).Mul(p.x, q.x))
	dx := new(big.Int).Add(big.NewInt(1), product)
	dy := new(big.Int).Sub(big.NewInt(1), product)
	// On the curve both denominators are nonzero. Share their inversion.
	inverse := new(big.Int).Mul(dx, dy)
	if inverse.ModInverse(inverse, mod) == nil {
		// Keep malformed hint inputs total, as in the individual divisions.
		nx.Set(ratio(mod, nx, dx))
		ny.Set(ratio(mod, ny, dy))
	} else {
		nx.Mul(nx, dy).Mul(nx, inverse).Mod(nx, mod)
		ny.Mul(ny, dx).Mul(ny, inverse).Mod(ny, mod)
	}
	return hostPoint{nx, ny}
}
func addHint(q *big.Int, in, out []*big.Int) error {
	return emfield.Unwrap(q, in, out, func(_ *big.Int, _, values, outputs []*big.Int) error {
		if len(values) != 4 || len(outputs) != 2 {
			return errors.New("ed25519 addition shape")
		}
		r := hostAdd(hostPoint{values[0], values[1]}, hostPoint{values[2], values[3]})
		outputs[0].Set(r.x)
		outputs[1].Set(r.y)
		return nil
	})
}
func doubleHint(q *big.Int, in, out []*big.Int) error {
	return emfield.Unwrap(q, in, out, func(_ *big.Int, _, values, outputs []*big.Int) error {
		if len(values) != 2 || len(outputs) != 2 {
			return errors.New("ed25519 doubling shape")
		}
		p := hostPoint{values[0], values[1]}
		r := hostAdd(p, p)
		outputs[0].Set(r.x)
		outputs[1].Set(r.y)
		return nil
	})
}

