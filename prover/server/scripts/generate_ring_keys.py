#!/usr/bin/env python3
"""Generate custom-ring keys and shared Rust and TypeScript catalogs.

This performs fresh local Groth16 setups. It does not publish artifacts.
Run the compiled-circuit/key and cross-language proof checks before release.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile


SERVER = Path(__file__).resolve().parents[1]
REPO = SERVER.parents[1]
INTERFACE = REPO / "custom-rings/interface/src"
LOCK = SERVER / "prover/provingkeys/proving-keys.lock"
CHECK = False

def write(path, content):
    if path.suffix == ".rs":
        content = subprocess.check_output(["rustfmt", "--config-path", str(REPO / "rustfmt.toml"), "--emit", "stdout"], input=content, text=True)
    if CHECK:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"stale generated catalog: {path.relative_to(REPO)}")
    else:
        path.write_text(content)


def digest(path):
    with path.open("rb") as data:
        return hashlib.file_digest(data, "sha256").hexdigest()


def catalog(entries):
    lines = [
        "//! Generated by generate_ring_keys.py from the Go circuit catalog.",
        "use groth16_solana::groth16::Groth16Verifyingkey;",
        "",
    ]
    for entry in entries:
        module = entry["module"]
        lines += [f'#[path = "{module}.rs"]', f"mod {module};"]
    lines += [
        "",
        "pub const SHAPED_PROVING_KEY_SHA256S: &[(&str, [u8; 32])] = &[",
    ]
    for entry in sorted(entries, key=lambda e: e["file"]):
        lines += [
            f'    ("{entry["file"]}", {entry["module"]}::VERIFYINGKEY_PROVING_KEY_SHA256),'
        ]
    lines += [
        "];",
        "",
        "pub fn policy_shape_key(",
        "    inputs: usize, outputs: usize, anonymous: bool, delegate: bool, subtree: bool,",
        ") -> Option<&'static Groth16Verifyingkey<'static>> {",
        "    match (inputs, outputs, anonymous, delegate, subtree) {",
    ]
    for entry in entries:
        key = ", ".join(str(entry[k]).lower() for k in (
            "inputs", "outputs", "anonymous", "delegate", "subtree"
        ))
        lines += [f'        ({key}) => Some(&{entry["module"]}::VERIFYINGKEY),']
    lines += ["        _ => None,", "    }", "}", ""]
    write(INTERFACE / "shaped_verifying_keys.rs", "\n".join(lines))



def base_catalog(entries):
    lines = [
        "//! Generated by generate_ring_keys.py from the Go circuit catalog.",
        "macro_rules! verifying_keys {",
        "    ($($module:ident => $key:literal,)*) => {",
        "        $(pub mod $module;)*",
        "        /// File names and the proving-key hashes pinned by their verifiers.",
        "        pub const PROVING_KEY_SHA256S: &[(&str, [u8; 32])] =",
        "            &[$(($key, $module::VERIFYINGKEY_PROVING_KEY_SHA256),)*];",
        "    };",
        "}",
        "verifying_keys! {",
    ]
    for entry in entries:
        lines += [f'    {entry["module"]} => "{entry["file"]}",']
    lines += ["}", ""]
    # This file is included at the crate root, keeping each module's existing path.
    write(INTERFACE / "verifying_keys.rs", "\n".join(lines).replace("//! Generated", "// Generated"))


def typescript_catalog(entries):
    lines = [
        "// Generated by generate_ring_keys.py from proving-keys.lock.",
        "export const RING_PROVING_KEY_SHA256S: Readonly<Record<string, string>> = Object.freeze({",
    ]
    for entry in sorted(entries, key=lambda e: e["file"]):
        line = f'  "{entry["file"]}": "{entry["sha256"]}",'
        if len(line) > 100:
            lines += [f'  "{entry["file"]}":', f'    "{entry["sha256"]}",']
        else:
            lines.append(line)
    lines += ["});", ""]
    write(REPO / "sdk-libs/ts/src/interface/ring-proving-keys.ts", "\n".join(lines))


def release_catalog(entries):
    lines = [
        "//! Generated by generate_ring_keys.py from the Go circuit catalog.",
        "//! Shared by artifact staging and the CLI. This module contains no verifying keys.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct RingKey { pub section: &'static str, pub circuit: &'static str }",
        "impl RingKey {",
        'pub const CONFIDENTIAL_AUDIT: Self = Self::new("confidential_audit_key", "custom-ring-base-confidential");',
        "const fn new(section: &'static str, circuit: &'static str) -> Self { Self { section, circuit } }",
        f"pub const ALL: [Self; {len(entries)}] = [",
    ]
    for e in entries:
        lines += [f'Self::new("{e["section"]}", "{e["circuit"]}"),']
    lines += [
        "];",
        "pub fn file_name(self) -> String { format!(\"{}.key\", self.circuit.replace('-', \"_\")) }",
        "pub const fn circuit(self) -> &'static str { self.circuit }",
        'pub fn asset(self, tag: &str) -> String { let suffix = if self.section == "register_key" { "" } else { "-key" }; format!("{}{suffix}-{tag}.key", self.circuit) }',
        "}", "",
    ]
    write(INTERFACE / "key_catalog.rs", "\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prover", type=Path, default=REPO / "target/prover-server")
    parser.add_argument("--catalog-only", action="store_true", help="refresh metadata from existing pins without rotating keys")
    parser.add_argument("--check", action="store_true", help="reject stale catalogs without writing or rotating keys")
    parser.add_argument("--only", action="append", default=[], help="set up only this newly added circuit, preserving existing pins")
    parser.add_argument("--xtask", type=Path, default=REPO / "target/debug/xtask")
    parser.add_argument("--keys-dir", type=Path, default=SERVER / "proving-keys")
    parser.add_argument("--jobs", type=int, default=2)
    parser.add_argument("--metadata", type=Path)
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    prover, xtask = args.prover.resolve(), args.xtask.resolve()
    keys = args.keys_dir.resolve()
    entries = json.loads(subprocess.check_output(
        ["go", "run", "./cmd/ring-shapes", "--keys"], cwd=SERVER, text=True
    ))
    global CHECK
    CHECK = args.check
    if not (args.catalog_only or args.check):
        keys.mkdir(parents=True, exist_ok=True)
        selected = [entry for entry in entries if not args.only or entry["circuit"] in args.only]
        if args.only and len(selected) != len(args.only):
            parser.error("--only must name each selected circuit exactly once")
        generate_keys(args, selected, prover, xtask, keys)
    pins = json.loads(LOCK.read_text())["keys"]
    files = [entry["file"] for entry in entries]
    expected = {name for name in pins if name.startswith("custom_ring_")}
    if len(files) != len(set(files)) or set(files) != expected:
        raise SystemExit("Go ring catalog must name every pinned custom-ring key exactly once")
    for entry in entries:
        entry.update(pins[entry["file"]])
    shaped = [entry for entry in entries if entry["inputs"]]
    base_catalog([entry for entry in entries if not entry["inputs"]])
    catalog(shaped)
    typescript_catalog(entries)
    release_catalog(entries)
    fields = ("circuit", "inputs", "outputs", "anonymous", "delegate", "subtree")
    manifest = [{field: entry[field] for field in fields} for entry in shaped]
    write(REPO / "custom-rings/policy-shapes.json", json.dumps(manifest, indent=2) + "\n")
    if args.metadata:
        write(args.metadata, json.dumps(entries, indent=2) + "\n")
    print(f"{'checked' if CHECK else 'updated'} catalogs for {len(entries)} ring keys", flush=True)


def generate_keys(args, entries, prover, xtask, keys):
    env = dict(os.environ, GOMAXPROCS=str(max(1, (os.cpu_count() or 2) // args.jobs)))
    with tempfile.TemporaryDirectory(prefix="ring-shaped-keys-") as temporary:
        temporary = Path(temporary)

        def generate(entry):
            circuit = entry["circuit"]
            stem = entry["file"].removesuffix(".key")
            key = keys / entry["file"]
            vk = temporary / (stem + ".vkbin")
            with (temporary / (stem + ".log")).open("w+") as log:
                try:
                    subprocess.run(
                        [str(prover), "setup-" + circuit, "--output", str(key), "--vk-out", str(vk)],
                        cwd=SERVER, env=env, stdout=log, stderr=log, check=True,
                    )
                    subprocess.run(
                        [str(xtask), "bsb22-vk", str(vk), str(key), str(INTERFACE), entry["module"] + ".rs"],
                        cwd=REPO, stdout=log, stderr=log, check=True,
                    )
                except subprocess.CalledProcessError:
                    log.seek(0)
                    print(log.read(), flush=True)
                    raise
            entry["sha256"], entry["size"] = digest(key), key.stat().st_size
            print(f"generated {circuit} ({entry['size']} bytes)", flush=True)
            return entry

        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            entries = list(pool.map(generate, entries))

    flags = [flag for entry in entries for flag in ("--release", entry["file"])]
    subprocess.run([
        "python3", str(SERVER / "scripts/generate_lockfile.py"), str(keys),
        *flags, "--only-release",
    ], check=True)


if __name__ == "__main__":
    main()
