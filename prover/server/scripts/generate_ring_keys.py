#!/usr/bin/env python3
"""Set up the ring keys, export their verifying keys and write the catalogs that pin them.

Setups run locally and publish nothing, a rotation over several hosts runs --setup-only --shard I/N
on each, then --export-only over the gathered keys.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time


SERVER = Path(__file__).resolve().parents[1]
REPO = SERVER.parents[1]
INTERFACE = REPO / "custom-rings/interface/src"
LOCK = SERVER / "prover/provingkeys/proving-keys.lock"
TS_CATALOG = REPO / "sdk-libs/ts/src/interface/ring-proving-keys.ts"
GENERATED = "Generated by generate_ring_keys.py from the Go circuit catalog."


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--setup-only", action="store_true", help="set up the selected keys, export nothing")
    mode.add_argument("--export-only", action="store_true", help="export every ring key in --keys-dir and repin it")
    mode.add_argument("--catalog-only", action="store_true", help="rewrite the catalogs from the lock pins")
    mode.add_argument("--check", action="store_true", help="reject a stale catalog, write nothing")
    mode.add_argument("--list", action="store_true", help="print the selected keys in setup order with their sizes")
    parser.add_argument("--spp", action="store_true", help="also select the SPP ring rail keys that rotate with the ring keys")
    parser.add_argument("--only", action="append", default=[], metavar="KEY", help="select this key file, repeatable")
    parser.add_argument("--shard", metavar="I/N", help="select host I of N, every host balancing the same constraint totals")
    parser.add_argument("--missing", action="store_true", help="skip selected keys already in --keys-dir")
    parser.add_argument("--jobs", type=int, default=2, help="setups run at once")
    parser.add_argument("--keys-dir", type=Path, default=SERVER / "proving-keys")
    parser.add_argument("--prover", type=Path, default=REPO / "target/prover-server")
    parser.add_argument("--xtask", type=Path, default=REPO / "target/debug/xtask")
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    keys = args.keys_dir.resolve()

    if args.check or args.catalog_only:
        write_catalogs(catalog(), check=args.check)
        return
    if args.export_only:
        export(args, catalog(), keys)
        return
    selected = select(args, parser, catalog())
    if args.list:
        for entry in selected:
            print(f"{entry['file']:45} {entry['constraints']:>11,} constraints {entry['public']} public {entry['commitments']} bsb22")
        return
    setup(args, selected, keys)
    if not args.setup_only:
        export(args, catalog(), keys)


def catalog(compile_files=()):
    command = ["go", "run", "./cmd/ring-shapes"]
    if compile_files:
        command += ["--compile", *compile_files]
    return json.loads(subprocess.check_output(command, cwd=SERVER, text=True))


def select(args, parser, entries):
    """The keys this host sets up, ascending constraints so the narrow shapes finish first."""
    chosen = [entry for entry in entries if entry["kind"] == "ring" or args.spp]
    if args.only:
        names = {name.removesuffix(".key") + ".key" for name in args.only}
        chosen = [entry for entry in chosen if entry["file"] in names]
        if len(chosen) != len(names):
            parser.error("--only names a key outside the selection: " + ", ".join(sorted(names - {e["file"] for e in chosen})))
    sizes = {entry["file"]: entry for entry in catalog([entry["file"] for entry in chosen])}
    chosen = sorted((sizes[entry["file"]] for entry in chosen), key=lambda entry: (entry["constraints"], entry["file"]))
    if args.shard:
        try:
            index, count = (int(part) for part in args.shard.split("/"))
        except ValueError:
            parser.error("--shard takes I/N")
        if not 1 <= index <= count:
            parser.error("--shard takes I/N with 1 <= I <= N")
        loads = [0] * count
        hosts = {}
        # Largest first onto the least loaded host keeps the hosts within one key of each other.
        for entry in sorted(chosen, key=lambda entry: (-entry["constraints"], entry["file"])):
            host = loads.index(min(loads))
            loads[host] += entry["constraints"]
            hosts[entry["file"]] = host
        chosen = [entry for entry in chosen if hosts[entry["file"]] == index - 1]
    if args.missing:
        keys = args.keys_dir.resolve()
        chosen = [entry for entry in chosen if not (keys / entry["file"]).exists()]
    return chosen


def setup(args, entries, keys):
    keys.mkdir(parents=True, exist_ok=True)
    prover = args.prover.resolve()
    env = dict(os.environ, GOMAXPROCS=str(max(1, (os.cpu_count() or 2) // args.jobs)))
    # A key reaches its final name only once its setup finished, a killed run leaves no partial key.
    with tempfile.TemporaryDirectory(prefix="ring-key-setup-", dir=keys) as staging:
        staging = Path(staging)

        def run(entry):
            output = staging / entry["file"]
            started = time.monotonic()
            with (staging / (entry["file"] + ".log")).open("w+") as log:
                try:
                    subprocess.run([str(prover), *entry["setup"], "--output", str(output)],
                                   cwd=SERVER, env=env, stdout=log, stderr=log, check=True)
                except subprocess.CalledProcessError:
                    log.seek(0)
                    print(log.read(), flush=True)
                    raise
            os.replace(output, keys / entry["file"])
            print(f"set up {entry['file']} in {time.monotonic() - started:.0f} s", flush=True)

        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            list(pool.map(run, entries))


def export(args, entries, keys):
    """Pins exactly the ring keys in keys, a key absent there loses its pin and its verifying key."""
    present = [entry for entry in entries if entry["kind"] == "ring" and (keys / entry["file"]).exists()]
    if not present:
        raise SystemExit(f"no ring key in {keys}")
    prover, xtask = args.prover.resolve(), args.xtask.resolve()
    with tempfile.TemporaryDirectory(prefix="ring-vk-") as temporary:
        for entry in present:
            key, vk = keys / entry["file"], Path(temporary) / (entry["file"] + ".vkbin")
            subprocess.run([str(prover), "export-vk", "--keys-file", str(key), "--output", str(vk)], cwd=SERVER, check=True, capture_output=True)
            subprocess.run([str(xtask), "bsb22-vk", str(vk), str(key), str(INTERFACE), entry["module"] + ".rs"], cwd=REPO, check=True, capture_output=True)
            print(f"exported {entry['module']}", flush=True)
    subprocess.run([
        "python3", str(SERVER / "scripts/generate_lockfile.py"), str(keys), "--only-release",
        *(flag for entry in present for flag in ("--release", entry["file"])),
    ], check=True)
    exported = {entry["module"] + ".rs" for entry in present}
    for module in INTERFACE.glob("*_verifying_key.rs"):
        if module.name not in exported:
            module.unlink()
    write_catalogs(entries, check=False)
    missing = [entry["file"] for entry in entries if entry["kind"] == "ring" and entry not in present]
    if missing:
        print("not yet set up: " + ", ".join(missing), flush=True)


def write_catalogs(entries, check):
    pins = json.loads(LOCK.read_text())["keys"]
    ring = [entry for entry in entries if entry["kind"] == "ring"]
    pinned = [entry for entry in ring if entry["file"] in pins]
    stale = sorted(set(name for name in pins if name.startswith("custom_ring_")) - {entry["file"] for entry in ring})
    modules = {entry["module"] + ".rs" for entry in pinned}
    unpinned = sorted(path.name for path in INTERFACE.glob("*_verifying_key.rs") if path.name not in modules)
    absent = sorted(module for module in modules if not (INTERFACE / module).exists())
    if check and (stale or unpinned or absent):
        raise SystemExit(f"stale ring key pins {stale}, verifying keys of no pinned key {unpinned}, pinned keys without a verifying key {absent}")
    # Until --export-only writes its module a pinned key gets no lookup arm, the program refuses its proofs.
    exported = [entry for entry in pinned if entry["module"] + ".rs" not in absent]
    write(INTERFACE / "verifying_keys.rs", rust(verifying_keys(exported)), check)
    write(INTERFACE / "ring_keys.rs", rust(ring_keys(ring)), check)
    write(TS_CATALOG, typescript(pinned, pins), check)
    print(f"{'checked' if check else 'wrote'} the catalogs of {len(ring)} ring keys, {len(pinned)} pinned", flush=True)


def verifying_keys(exported):
    lines = [
        "// " + GENERATED,
        "macro_rules! verifying_keys {",
        "    ($($module:ident => $key:literal,)*) => {",
        "        $(pub mod $module;)*",
        "        /// File names and the proving-key hashes pinned by their verifiers.",
        "        pub const PROVING_KEY_SHA256S: &[(&str, [u8; 32])] =",
        "            &[$(($key, $module::VERIFYINGKEY_PROVING_KEY_SHA256),)*];",
        "    };",
        "}",
        "verifying_keys! {",
        *(f'    {entry["module"]} => "{entry["file"]}",' for entry in exported),
        "}",
        "",
        "/// The key `circuit` verifies under, filled by the key rotation.",
    ]
    if not exported:
        return lines + [
            "pub fn verifying_key(_circuit: key_catalog::RingCircuit) -> Option<&'static groth16_solana::groth16::Groth16Verifyingkey<'static>> {",
            "    None",
            "}",
        ]
    return lines + [
        "pub fn verifying_key(circuit: key_catalog::RingCircuit) -> Option<&'static groth16_solana::groth16::Groth16Verifyingkey<'static>> {",
        "    match circuit {",
        *(f'        key_catalog::RingCircuit::{entry["rust"]} => Some(&{entry["module"]}::VERIFYINGKEY),' for entry in exported),
        "        _ => None,",
        "    }",
        "}",
    ]


def ring_keys(ring):
    return [
        "//! " + GENERATED,
        "use crate::key_catalog::{RingCircuit, RingKey};",
        "",
        f"pub const RING_KEYS: [RingKey; {len(ring)}] = [",
        *(f'    RingKey {{ circuit: RingCircuit::{entry["rust"]}, name: "{entry["circuit"]}" }},' for entry in ring),
        "];",
    ]


def typescript(pinned, pins):
    header = "export const RING_PROVING_KEY_SHA256S: Readonly<Record<string, string>> = Object.freeze({"
    if not pinned:
        return "\n".join(["// Generated by generate_ring_keys.py from proving-keys.lock.", header + "});", ""])
    lines = ["// Generated by generate_ring_keys.py from proving-keys.lock.", header]
    for entry in sorted(pinned, key=lambda entry: entry["file"]):
        line = f'  "{entry["file"]}": "{pins[entry["file"]]["sha256"]}",'
        lines += [f'  "{entry["file"]}":', f'    "{pins[entry["file"]]["sha256"]}",'] if len(line) > 100 else [line]
    return "\n".join(lines + ["});", ""])


def rust(lines):
    return subprocess.check_output(
        ["rustfmt", "--config-path", str(REPO / "rustfmt.toml"), "--emit", "stdout"],
        input="\n".join(lines) + "\n", text=True,
    )


def write(path, content, check):
    if not check:
        path.write_text(content)
    elif not path.exists() or path.read_text() != content:
        raise SystemExit(f"stale generated catalog: {path.relative_to(REPO)}")


if __name__ == "__main__":
    main()
