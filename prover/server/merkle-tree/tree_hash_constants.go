// The tree hash has one Go definition (gnark-crypto) and a Rust copy that
// cannot import it. WriteTreeHashConstants regenerates the Rust round keys,
// both zero tables and the shared test vectors from the Go definition so the
// copies cannot drift apart.
const (
	zeroTableHeight     = 40
	nullifierTreeHeight = 40
	rustRoundKeysPath   = "program-libs/hasher/src/poseidon2/round_keys.rs"
	rustZeroBytesPath   = "program-libs/hasher/src/zero_bytes/poseidon2.rs"
	goZeroBytesPath     = "prover/server/merkle-tree/zero_bytes.go"
	vectorsPath         = "test-vectors/tree_hash.json"
	generatedHeader     = "// Generated by `light-prover tree-hash-constants`. Do not edit."
)

type treeHashVectors struct {
	Parameters struct {
		Width         int    `json:"width"`
		FullRounds    int    `json:"full_rounds"`
		PartialRounds int    `json:"partial_rounds"`
		Seed          string `json:"seed"`
	} `json:"parameters"`
	Compress []struct {
		Left  string `json:"left"`
		Right string `json:"right"`
		Hash  string `json:"hash"`
	} `json:"compress"`
	ZeroNodes         []string `json:"zero_nodes"`
	NullifierInitRoot string   `json:"nullifier_tree_init_root_40"`
}

func WriteTreeHashConstants(repoRoot string) error {
	params := poseidon2.NewParameters(TreeHashWidth, TreeHashFullRounds, TreeHashPartialRounds)
	zero := ZeroNodes(zeroTableHeight)

	files := map[string]string{
		rustRoundKeysPath: rustRoundKeys(params),
		rustZeroBytesPath: rustZeroBytes(zero, generatedHeader, "use super::ZeroBytes;\npub const ZERO_BYTES: ZeroBytes = "),
		goZeroBytesPath:   goZeroBytes(zero),
		vectorsPath:       vectors(params, zero),
	}
	for rel, content := range files {
		path := filepath.Join(repoRoot, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func rustBytes(v [32]byte) string {
	parts := make([]string, 32)
	for i, b := range v {
		parts[i] = fmt.Sprintf("%d", b)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// Round keys in permutation order as `ark_ff::MontFp!` constants:
// `FULL_ROUND_KEYS` holds the first and last `full_rounds / 2` rounds, one
// key per lane; `PARTIAL_ROUND_KEYS` holds one key (lane 0) per partial round.
func rustRoundKeys(p *poseidon2.Parameters) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\n", generatedHeader)
	fmt.Fprintf(&b, "//! Poseidon2 round keys, %s.\n\n", p.String())
	b.WriteString("use ark_bn254::Fr;\nuse ark_ff::MontFp;\n\n")
	key := func(e fr.Element) string {
		return fmt.Sprintf("MontFp!(\"%s\")", e.BigInt(new(big.Int)).String())
	}
	half := p.NbFullRounds / 2
	fmt.Fprintf(&b, "pub const FULL_ROUND_KEYS: [[Fr; %d]; %d] = [\n", p.Width, p.NbFullRounds)
	writeFull := func(i int) {
		b.WriteString("    [\n")
		for j := 0; j < p.Width; j++ {
			fmt.Fprintf(&b, "        %s,\n", key(p.RoundKeys[i][j]))
		}
		b.WriteString("    ],\n")
	}
	for i := 0; i < half; i++ {
		writeFull(i)
	}
	for i := half + p.NbPartialRounds; i < p.NbFullRounds+p.NbPartialRounds; i++ {
		writeFull(i)
	}
	b.WriteString("];\n\n")
	fmt.Fprintf(&b, "pub const PARTIAL_ROUND_KEYS: [Fr; %d] = [\n", p.NbPartialRounds)
	for i := half; i < half+p.NbPartialRounds; i++ {
		fmt.Fprintf(&b, "    %s,\n", key(p.RoundKeys[i][0]))
	}
	b.WriteString("];\n")
	return b.String()
}

func rustZeroBytes(zero [][32]byte, header, decl string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\n%s[\n", header, decl)
	for _, z := range zero {
		fmt.Fprintf(&b, "    %s,\n", rustBytes(z))
	}
	b.WriteString("];\n")
	return b.String()
}

func goZeroBytes(zero [][32]byte) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\npackage merkle_tree\n\n", generatedHeader)
	fmt.Fprintf(&b, "// ZERO_BYTES[i] is the root of an empty subtree of height i.\nvar ZERO_BYTES = [%d][32]byte{\n", len(zero))
	for _, z := range zero {
		parts := make([]string, 32)
		for i, v := range z {
			parts[i] = fmt.Sprintf("%d", v)
		}
		fmt.Fprintf(&b, "\t{%s},\n", strings.Join(parts, ", "))
	}
	b.WriteString("}\n")
	return b.String()
}

func vectors(p *poseidon2.Parameters, zero [][32]byte) string {
	var v treeHashVectors
	v.Parameters.Width = p.Width
	v.Parameters.FullRounds = p.NbFullRounds
	v.Parameters.PartialRounds = p.NbPartialRounds
	v.Parameters.Seed = p.String()

	one := big.NewInt(1)
	pMinusOne := new(big.Int).Sub(fr.Modulus(), one)
	inputs := [][2]*big.Int{
		{big.NewInt(0), big.NewInt(0)},
		{big.NewInt(1), big.NewInt(2)},
		{big.NewInt(2), big.NewInt(1)},
		{pMinusOne, pMinusOne},
		{big.NewInt(0), pMinusOne},
	}
	for _, in := range inputs {
		v.Compress = append(v.Compress, struct {
			Left  string `json:"left"`
			Right string `json:"right"`
			Hash  string `json:"hash"`
		}{hex32(in[0]), hex32(in[1]), hex32(TreeHash(in[0], in[1]))})
	}
	for _, z := range zero {
		v.ZeroNodes = append(v.ZeroNodes, hex.EncodeToString(z[:]))
	}

	// The nullifier tree starts with one leaf, (0, p-1), at index 0.
	root := TreeHash(big.NewInt(0), pMinusOne)
	for i := 0; i < nullifierTreeHeight; i++ {
		root = TreeHash(root, new(big.Int).SetBytes(zero[i][:]))
	}
	v.NullifierInitRoot = hex32(root)

	out, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		panic(err)
	}
	return string(out) + "\n"
}

func hex32(v *big.Int) string {
	var b [32]byte
	v.FillBytes(b[:])
	return hex.EncodeToString(b[:])
}
