package extractor

import (
	"fmt"
	"math/big"
	"strings"

	"github.com/consensys/gnark-crypto/ecc/secp256r1"

	"zolana/prover/circuits/verifiable-encryption/p256/emcurve"
)

// ExtractCombTables renders the fixed-base comb tables of the P-256 key
// agreement as Lean data. The output is committed as
// formal-verification/VerifiableEncryption/CombTables.lean, where a kernel
// certificate checks every entry against the curve group law. The doubled
// window bases are emitted alongside as certificate witnesses.
func ExtractCombTables() string {
	windows, topEven := emcurve.CombTables()
	var b strings.Builder
	b.WriteString("-- Generated by prover/extractor/comb_tables.go. Do not edit.\n\n")
	b.WriteString("namespace ZolanaVE.CombTables\n\n")
	b.WriteString("def windows : List (List (Nat × Nat)) := [\n")
	for t, window := range windows {
		b.WriteString("  [\n")
		writeEntries(&b, window, "    ")
		b.WriteString("  ]")
		if t != len(windows)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("]\n\n")
	b.WriteString("def topEven : List (Nat × Nat) := [\n")
	writeEntries(&b, topEven, "  ")
	b.WriteString("]\n\n")
	b.WriteString("def steps : List (Nat × Nat) := [\n")
	writeEntries(&b, combSteps(windows), "  ")
	b.WriteString("]\n\n")
	b.WriteString("end ZolanaVE.CombTables\n")
	return b.String()
}

// combSteps doubles each window base (selector 16, digit 1) below the top
// window. The Lean certificate uses them as the common difference between
// adjacent odd multiples, so the kernel never inverts a field element.
func combSteps(windows [][][2]*big.Int) [][2]*big.Int {
	steps := make([][2]*big.Int, len(windows)-1)
	for t := range steps {
		var base secp256r1.G1Affine
		base.X.SetBigInt(windows[t][16][0])
		base.Y.SetBigInt(windows[t][16][1])
		var doubled secp256r1.G1Affine
		doubled.Double(&base)
		steps[t] = [2]*big.Int{doubled.X.BigInt(new(big.Int)), doubled.Y.BigInt(new(big.Int))}
	}
	return steps
}

func writeEntries(b *strings.Builder, entries [][2]*big.Int, indent string) {
	for i, entry := range entries {
		separator := ","
		if i == len(entries)-1 {
			separator = ""
		}
		fmt.Fprintf(b, "%s(0x%s, 0x%s)%s\n", indent, entry[0].Text(16), entry[1].Text(16), separator)
	}
}
