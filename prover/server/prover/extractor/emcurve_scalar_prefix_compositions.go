// renderScalarPrefixComposition renders only the actual main/p1 prefix.
// Its explicit p2 continuation is supplied by the outer ladder assembly;
// no theorem here claims whole-ladder completeness from a success premise.
func renderScalarPrefixComposition(defs map[string]extractedDef) (string, error) {
	const name = "ScalarMulChecked_8_8_8_h903d3456"
	checks := []string{"CheckPolynomial_8_h57d6a69c", "CheckPolynomial_16_h93312e5c", "CheckPolynomial_32_h35a4bc86", "CheckPolynomial_16_h0c8d6bae", "CheckPolynomial_24_h2629e496"}
	checkLine := regexp.MustCompile(`^(CheckPolynomial_\d+_h[0-9a-f]{8}) `)
	zeroLine := regexp.MustCompile(`^∃gate_\d+, Gates\.is_zero `)
	selectLine := regexp.MustCompile(`^∃gate_\d+, Gates\.select `)
	vectors, ranges, zeros, bools, selects, ci := 0, 0, 0, 0, 0, 0
	widths := []int{25, 24, 24}
	for pi, part := range []string{name, name + "_p1"} {
		d, ok := defs[part]
		if !ok {
			return "", fmt.Errorf("missing scalar prefix fragment %s", part)
		}
		continuations := 0
		for _, line := range d.body {
			l := strings.TrimSpace(strings.TrimSuffix(line, " ∧"))
			switch {
			case checkLine.MatchString(l):
				got := checkLine.FindStringSubmatch(l)[1]
				if ci >= len(checks) || got != checks[ci] {
					return "", fmt.Errorf("%s: unexpected scalar prefix primitive %s", part, got)
				}
				if _, ok := defs[got]; !ok {
					return "", fmt.Errorf("%s: missing primitive %s", part, got)
				}
				ci++
			case vectorLine.MatchString(line):
				if vectors >= len(widths) || vectorLine.FindStringSubmatch(line)[1] != fmt.Sprint(widths[vectors]) {
					return "", fmt.Errorf("%s: unexpected scalar prefix vector hint", part)
				}
				vectors++
			case gateEqLine.MatchString(l):
			case rangeLine.MatchString(l):
				want := "11"
				if ranges%3 == 2 {
					want = "10"
				}
				if ranges >= 48 || rangeLine.FindStringSubmatch(l)[1] != want {
					return "", fmt.Errorf("%s: unexpected scalar prefix range", part)
				}
				ranges++
			case zeroLine.MatchString(l):
				zeros++
			case selectLine.MatchString(l):
				selects++
			case strings.HasPrefix(l, "Gates.is_bool "):
				bools++
			case strings.HasPrefix(l, "Gates.eq "):
			case strings.HasPrefix(l, fmt.Sprintf("%s_p%d ", name, pi+1)):
				continuations++
			default:
				return "", fmt.Errorf("%s: unsupported scalar prefix constraint %q", part, l)
			}
		}
		if continuations != 1 || (pi == 0 && (vectors != 1 || ranges != 24 || zeros != 3 || selects != 0)) {
			return "", fmt.Errorf("%s: changed scalar prefix boundary", part)
		}
	}
	if vectors != 3 || ranges != 48 || zeros != 6 || bools != 1 || selects != 22 || ci != len(checks) {
		return "", fmt.Errorf("incomplete scalar prefix schema: hints=%d ranges=%d zeros=%d bools=%d selects=%d checks=%d", vectors, ranges, zeros, bools, selects, ci)
	}
	w := &instanceWriter{}
	w.line("import VerifiableEncryption.Curve.CompletenessLadderGap")
	w.line("import VerifiableEncryption.Curve.CompletenessLadderExceptional")
	w.line("import VerifiableEncryption.Curve.CompletenessGeneratedQuadComposition")
	w.line("")
	w.line("-- GENERATED by prover/extractor/emcurve_scalar_prefix_compositions.go; do not edit.")
	w.line("-- Pure main/p1 composition. The outer mathematical assembly supplies the p2 continuation.")
	w.line("namespace ZolanaVE.P256.Completeness")
	w.line("open ZolanaVE.Field")
	w.line("open scoped BigOperators")
	w.line("set_option maxHeartbeats 0")
	w.line("set_option maxRecDepth 100000")
	w.line("")
	var atoms []string
	for i := 0; i < 8; i++ {
		atoms = append(atoms, fmt.Sprintf("(canonicalScalar original).limbs.get %d", i))
	}
	atoms = append(atoms, "2117178025", "2044519777", "3549155138", "3732110678", "4294967295", "2147483647", "2147483648", "2147483647")
	w.line("def scalarHalfInput (original : ℕ) : List.Vector F 16 := vec![%s]", strings.Join(atoms, ", "))
	atoms = nil
	for i := 0; i < 6; i++ {
		atoms = append(atoms, fmt.Sprintf("((canonicalScalar original).limbs.get %d - (exceptionalLimbs.get 3).get %d) ^ 2", i, i))
	}
	w.line("def scalarMinusThreePartial (original : ℕ) : F := %s", strings.Join(atoms, " + "))
	w.line("")
	w.line("/-- Compose the actual first two native fragments from explicit primitive witnesses,")
	w.line("constructed gap/exception hints, and the exact remaining p2 continuation. -/")
	w.line("theorem %s_prefix_compose (original : ℕ) (hr : RangeComplete)", name)
	w.line("    (PX PY Scalar L DX DY : List.Vector F 8) (rawL piecesL : List.Vector F 24)")
	w.line("    (hrL : ∀ i : Fin 8, RangeCheck 11 (piecesL.get ⟨3 * i.val, by omega⟩) ∧")
	w.line("      RangeCheck 11 (piecesL.get ⟨3 * i.val + 1, by omega⟩) ∧ RangeCheck 10 (piecesL.get ⟨3 * i.val + 2, by omega⟩))")
	w.line("    (hL : ∀ i : Fin 8, L.get i = piecesL.get ⟨3 * i.val, by omega⟩ +")
	w.line("      piecesL.get ⟨3 * i.val + 1, by omega⟩ * 2048 + piecesL.get ⟨3 * i.val + 2, by omega⟩ * 4194304 - 2147483648)")
	w.line("    (hScalar : ∀ k : List.Vector F 8 → Prop, k (canonicalScalar original).limbs → %s Scalar k)", checks[0])
	w.line("    (hHalf : ∀ k : List.Vector F 8 → Prop, k (halfScalarElem original).limbs → %s (scalarHalfInput original) k)", checks[1])
	w.line("    (hTangent : %s (quadTangentInput L PY PX))", checks[2])
	w.line("    (hDX : ∀ k : List.Vector F 8 → Prop, k DX → %s (quadDoubleXInput L PX) k)", checks[3])
	w.line("    (hDY : ∀ k : List.Vector F 8 → Prop, k DY → %s (quadDoubleYInput L PX DX PY) k)", checks[4])
	w.line("    (k : List.Vector (List.Vector F 8) 2 → Prop)")
	var rest []string
	rest = append(rest, "PX", "PY", "Scalar", "(canonicalScalar original).limbs", "(∑ i : Fin 6, exceptionalFlag original i)", "(halfScalarElem original).limbs")
	for _, coords := range []string{"DX PX", "DY PY"} {
		for i := 0; i < 8; i++ {
			rest = append(rest, fmt.Sprintf("((selectedPointLimbs original %s).get %d)", coords, i))
		}
	}
	for i := 0; i < 6; i++ {
		rest = append(rest, fmt.Sprintf("((selectedScalarElem original).limbs.get %d)", i))
	}
	rest = append(rest, "k")
	w.line("    (hTail : %s_p2 %s) :", name, strings.Join(rest, " "))
	w.line("    %s PX PY Scalar k := by", name)
	for i := 0; i < 8; i++ {
		w.line("  have hL%d := hL (%d : Fin 8)", i, i)
		w.line("  simp only [sub_eq_add_neg, mul_comm] at hL%d", i)
		w.line("  change L.get %d = piecesL.get %d + 2048 * piecesL.get %d + 4194304 * piecesL.get %d + -(2147483648 : F) at hL%d", i, 3*i, 3*i+1, 3*i+2, i)
		w.line("  have hG%d := scalarGapHint_limb original (%d : Fin 8)", i, i)
		w.line("  simp only [mul_comm] at hG%d", i)
		w.line("  change (canonicalNatElem (scalarGapNat original) (scalarGap_width original)).limbs.get %d =", i)
		w.line("    (scalarGapHint original).get %d + 2048 * (scalarGapHint original).get %d + 4194304 * (scalarGapHint original).get %d at hG%d", 3*i, 3*i+1, 3*i+2, i)
	}
	words := [][]string{
		{"1", "0", "0", "0", "0", "0", "0", "0"},
		{"4234356048", "4089039554", "2803342980", "3169254061", "4294967295", "4294967295", "0", "4294967295"},
		{"3", "0", "0", "0", "0", "0", "0", "0"},
		{"4234356046", "4089039554", "2803342980", "3169254061", "4294967295", "4294967295", "0", "4294967295"},
		{"2822904033", "1294370604", "437239555", "2112836041", "2863311530", "2863311530", "0", "2863311530"},
		{"1411452016", "2794668950", "2366103425", "1056418020", "1431655765", "1431655765", "0", "1431655765"},
	}
	var partialRewrites []string
	for i := 0; i < 6; i++ {
		var getters []string
		for j := 0; j < 8; j++ {
			fact := fmt.Sprintf("hC%d_%d", i, j)
			getters = append(getters, fact)
			if i == 3 {
				partialRewrites = append(partialRewrites, fact)
			}
			w.line("  have %s : (exceptionalLimbs.get %d).get %d = (%s : F) := rfl", fact, i, j, words[i][j])
		}
		w.line("  have hz%d := exceptionalFlag_native_spec original (%d : Fin 6)", i, i)
		w.line("  simp only [exceptionalSquared, Fin.sum_univ_eight, %s,", strings.Join(getters, ", "))
		w.line("    pow_two, sub_eq_add_neg, mul_comm, neg_zero, add_zero] at hz%d", i)
	}
	w.line("  have hDXNative := hDX")
	w.line("  have hDYNative := hDY")
	w.line("  simp only [quadDoubleXInput, sub_eq_add_neg, mul_comm] at hDXNative")
	w.line("  simp only [quadDoubleYInput, sub_eq_add_neg, mul_comm] at hDYNative")
	w.line("  have hsum := (Fin.sum_univ_six (fun i => exceptionalFlag original i)).symm")
	w.line("  have hPrefix : %s_p1 PX PY Scalar (canonicalScalar original).limbs", name)
	w.line("      (exceptionalFlag original 0 + exceptionalFlag original 1 + exceptionalFlag original 2)")
	w.line("      (scalarMinusThreePartial original) k := by")
	w.line("    unfold %s_p1", name)
	nativeWireSimp(w, "    ")
	w.line("    simp only [scalarMinusThreePartial, %s,", strings.Join(partialRewrites, ", "))
	w.line("      pow_two, sub_eq_add_neg, mul_comm, neg_zero, add_zero]")
	w.line("    refine ⟨exceptionalFlag original 3, hz3, exceptionalFlag original 4, hz4, exceptionalFlag original 5, hz5, ?_⟩")
	w.line("    apply hHalf")
	items := append([]string{"rawL", "piecesL"}, nativeRangeFacts("hrL", 0, 24)...)
	items = append(items, "?_", "?_")
	w.line("    refine %s", tupleOf(items))
	w.line("    · simp only [← hL0, ← hL1, ← hL2, ← hL3, ← hL4, ← hL5, ← hL6, ← hL7]")
	w.line("      simpa only [quadTangentInput, quadCompositionA] using hTangent")
	w.line("    · simp only [← hL0, ← hL1, ← hL2, ← hL3, ← hL4, ← hL5, ← hL6, ← hL7]")
	w.line("      apply hDXNative")
	w.line("      apply hDYNative")
	w.line("      simp only [hsum]")
	items = nil
	for _, coords := range []string{"DX PX", "DY PY"} {
		for i := 0; i < 8; i++ {
			items = append(items, fmt.Sprintf("(selectedPointLimbs original %s).get %d", coords, i), fmt.Sprintf("selectedPointLimbs_native_select original %s %d", coords, i))
		}
	}
	for i := 0; i < 6; i++ {
		items = append(items, fmt.Sprintf("(selectedScalarElem original).limbs.get %d", i), fmt.Sprintf("selectedScalarElem_native_select original %d", i))
	}
	items = append(items, "hTail")
	w.line("      exact %s", tupleOf(items))
	w.line("  unfold %s", name)
	w.line("  apply hScalar")
	nativeWireSimp(w, "  ")
	w.line("  simp only [GatesDef.eq, neg_zero, add_zero]")
	items = []string{"scalarGapHint original"}
	for i := 0; i < 8; i++ {
		items = append(items, fmt.Sprintf("(scalarGapHint_ranges hr original %d).1", i), fmt.Sprintf("(scalarGapHint_ranges hr original %d).2.1", i), fmt.Sprintf("(scalarGapHint_ranges hr original %d).2.2", i))
	}
	items = append(items, "?_", "?_", "?_", "exceptionalFlag original 0", "hz0", "exceptionalFlag original 1", "hz1", "exceptionalFlag original 2", "hz2", "?_")
	w.line("  refine %s", tupleOf(items))
	w.line("  · simpa only [Gates, GatesGnark12, GatesGnark9, GatesGnark8] using scalarGapHint_bool original")
	for i := 0; i < 2; i++ {
		w.line("  · simp only [← hG0, ← hG1, ← hG2, ← hG3, ← hG4, ← hG5, ← hG6, ← hG7]")
		w.line("    have hg := (scalarGap_native_checks original).%d", i+1)
		w.line("    dsimp only [nativeGapLow, nativeGapHigh] at hg")
		w.line("    linear_combination hg")
	}
	w.line("  · simpa only [scalarMinusThreePartial, %s,", strings.Join(partialRewrites, ", "))
	w.line("      pow_two, sub_eq_add_neg, mul_comm, neg_zero, add_zero] using hPrefix")
	w.line("")
	w.line("end ZolanaVE.P256.Completeness")
	return w.b.String(), nil
}
