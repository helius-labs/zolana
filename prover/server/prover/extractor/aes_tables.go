package extractor

import (
	"fmt"
	"math/big"
	"strings"

	"zolana/prover/circuits/verifiable-encryption/aes"
)

const (
	aesTableRegionSize     = 256
	aesSubstitutionRegions = 5
)

// ExtractAesTables renders the AES lookup tables as the generated Lean module
// formal-verification/VerifiableEncryption/AesTables.lean. The substitution
// table is split into its five 256-entry regions in lookup insertion order, so
// region r holds the entries at lookup indices 256*r .. 256*r+255.
func ExtractAesTables() string {
	substitution := aes.SubstitutionTable()
	if len(substitution) != aesSubstitutionRegions*aesTableRegionSize {
		panic(fmt.Sprintf("aes tables: substitution has %d entries", len(substitution)))
	}
	sbox := aes.SboxTable()

	var b strings.Builder
	b.WriteString("-- Code generated by prover/extractor/aes_tables.go. DO NOT EDIT.\n\n")
	b.WriteString("namespace ZolanaVE.AesTables\n\n")
	for region := 0; region < aesSubstitutionRegions; region++ {
		start := region * aesTableRegionSize
		writeBigList(&b, fmt.Sprintf("substitution%d", region), substitution[start:start+aesTableRegionSize])
	}
	b.WriteString("def substitution : List (List Nat) :=\n  [substitution0, substitution1, substitution2, substitution3, substitution4]\n\n")
	writeBigList(&b, "spreadBytes", aes.SpreadByteTable())
	parity := aes.ChunkParityTable()
	parityValues := make([]string, len(parity))
	for i, value := range parity {
		parityValues[i] = fmt.Sprint(value)
	}
	writeList(&b, "chunkParity", parityValues)
	sboxValues := make([]string, len(sbox))
	for i, value := range sbox {
		sboxValues[i] = fmt.Sprint(value)
	}
	writeList(&b, "sboxTable", sboxValues)

	b.WriteString("theorem substitution_length : substitution.length = 5 := by rfl\n\n")
	for region := 0; region < aesSubstitutionRegions; region++ {
		fmt.Fprintf(&b, "theorem substitution%d_length : substitution%d.length = 256 := by rfl\n\n", region, region)
	}
	b.WriteString("theorem spreadBytes_length : spreadBytes.length = 256 := by rfl\n\n")
	b.WriteString("theorem chunkParity_length : chunkParity.length = 1296 := by rfl\n\n")
	b.WriteString("theorem sboxTable_length : sboxTable.length = 256 := by rfl\n\n")
	b.WriteString("end ZolanaVE.AesTables\n")
	return b.String()
}

func writeBigList(b *strings.Builder, name string, values []*big.Int) {
	rendered := make([]string, len(values))
	for i, value := range values {
		rendered[i] = value.String()
	}
	writeList(b, name, rendered)
}

func writeList(b *strings.Builder, name string, values []string) {
	const perLine = 8
	fmt.Fprintf(b, "def %s : List Nat := [\n", name)
	for start := 0; start < len(values); start += perLine {
		end := min(start+perLine, len(values))
		b.WriteString("  ")
		b.WriteString(strings.Join(values[start:end], ", "))
		if end < len(values) {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("]\n\n")
}
