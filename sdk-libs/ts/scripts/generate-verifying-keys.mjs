// Writes src/interface/verifying-keys.ts from the verifying keys the Rust
// interface crate compiles in, program-libs/interface/src/verifying_keys.
// Run after those keys are regenerated: `node scripts/generate-verifying-keys.mjs`.
// test/verifying-keys.test.ts fails until the two agree.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const RUST = new URL("../../../program-libs/interface/src/verifying_keys/", import.meta.url);
const OUT = new URL("../src/interface/verifying-keys.ts", import.meta.url);

function bytesHex(source, length, what) {
  const bytes = [...source.matchAll(/(\d+)u8/gu)].map((match) => Number(match[1]));
  if (bytes.length !== length || bytes.some((byte) => byte > 255)) {
    throw new Error(`${what}: expected ${length} bytes, found ${bytes.length}`);
  }
  return Buffer.from(bytes).toString("hex");
}

function array(source, name, length, file) {
  const match = new RegExp(`\\b${name}: \\[([^\\]]*)\\]`, "u").exec(source);
  if (match === null) throw new Error(`${file}: no ${name}`);
  return bytesHex(match[1], length, `${file} ${name}`);
}

function verifyingKey(file) {
  const source = readFileSync(new URL(file, RUST), "utf8");
  if (!/\bnr_pubinputs: 1,/u.test(source)) throw new Error(`${file}: not one public input`);
  const icBlock = /VERIFYINGKEY_VK_IC: &\[\[u8; 64\]\] = &\[([\s\S]*?)\];/u.exec(source);
  if (icBlock === null) throw new Error(`${file}: no vk_ic`);
  const ic = [...icBlock[1].matchAll(/\[([^\]]*)\]/gu)].map((match) =>
    bytesHex(match[1], 64, `${file} vk_ic`),
  );
  const committed = /\bvk_commitment: Some\(CommitmentVerifyingKey \{/u.test(source);
  if (!committed && !/\bvk_commitment: None,/u.test(source)) {
    throw new Error(`${file}: unreadable vk_commitment`);
  }
  if (ic.length !== (committed ? 3 : 2)) throw new Error(`${file}: ${ic.length} vk_ic entries`);
  return {
    alphaG1: array(source, "vk_alpha_g1", 64, file),
    betaG2: array(source, "vk_beta_g2", 128, file),
    gammaG2: array(source, "vk_gamma_g2", 128, file),
    deltaG2: array(source, "vk_delta_g2", 128, file),
    ic,
    ...(committed
      ? {
          commitment: {
            g2: array(source, "g2", 128, file),
            gSigmaNegG2: array(source, "g_sigma_neg_g2", 128, file),
          },
        }
      : {}),
  };
}

const files = readdirSync(RUST)
  .filter((file) => file.endsWith(".rs") && file !== "mod.rs" && file !== "circuit.rs")
  .sort();
const lines = [
  "// Generated by scripts/generate-verifying-keys.mjs from",
  "// program-libs/interface/src/verifying_keys. Do not edit by hand.",
  "",
  "/**",
  " * A Groth16 verifying key in the shielded pool's encoding, every point as",
  " * lowercase hex: a G1 point is `x || y` and a G2 point `x.c1 || x.c0 || y.c1",
  " * || y.c0`, each coordinate 32 big-endian bytes. `ic` holds one entry more",
  " * than the statement has public inputs, plus the BSB22 commitment's when",
  " * `commitment` is present.",
  " */",
  "export type Groth16VerifyingKey = Readonly<{",
  "  alphaG1: string;",
  "  betaG2: string;",
  "  gammaG2: string;",
  "  deltaG2: string;",
  "  ic: readonly string[];",
  "  commitment?: Readonly<{ g2: string; gSigmaNegG2: string }>;",
  "}>;",
  "",
  "/**",
  " * The verifying key of every circuit the shielded pool verifies, by its",
  " * proving key's file name, as Rust `spr_interface::verifying_keys` compiles",
  " * them. `test/verifying-keys.test.ts` pins this table to those sources.",
  " */",
  "export const VERIFYING_KEYS: Readonly<Record<string, Groth16VerifyingKey>> = Object.freeze({",
];
for (const file of files) {
  const key = verifyingKey(file);
  lines.push(`  "${file.replace(/\.rs$/u, ".key")}": {`);
  for (const field of ["alphaG1", "betaG2", "gammaG2", "deltaG2"]) {
    lines.push(`    ${field}:`, `      "${key[field]}",`);
  }
  lines.push("    ic: [", ...key.ic.map((point) => `      "${point}",`), "    ],");
  if (key.commitment !== undefined) {
    lines.push(
      "    commitment: {",
      `      g2: "${key.commitment.g2}",`,
      "      gSigmaNegG2:",
      `        "${key.commitment.gSigmaNegG2}",`,
      "    },",
    );
  }
  lines.push("  },");
}
lines.push("});", "");
writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${files.length} verifying keys`);
