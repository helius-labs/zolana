await initializePoseidon();

function hex<T extends Uint8Array>(value: string, length: number): T {
  const decoded = Uint8Array.from(Buffer.from(value, "hex"));
  if (decoded.length !== length) throw new RangeError(`expected ${String(length)} bytes`);
  return decoded as T;
}

function field(value: string): Bytes32 {
  return hex<Bytes32>(value, 32);
}

function need<T>(value: T | undefined, name: string): T {
  if (value === undefined) throw new Error(`vector slot without ${name}`);
  return value;
}

type Case = (typeof anonymous.cases)[number];
type VectorSlot = Case["slots"][number];

const ZERO = new Uint8Array(32) as Bytes32;

/** Generated by custom-rings/client/tests/disclosure_vectors.rs. */
describe.each(anonymous.cases.map((vector) => [vector.name, vector] as const))(
  "shared anonymous %s audit disclosure vector",
  (_name, vector) => {
    const key = {
      txViewingSecret: field(vector.tx_viewing_sk),
      salt: hex<Bytes16>(vector.salt, 16),
    };
    const firstNullifier = field(vector.first_nullifier);
    const seedOut = field(vector.seed_out);
    const ringId = field(vector.ring_id);
    const exits = (vector.layout & 1) !== 0;
    const entry = vector.key === "entry";
    const slotExits = vector.slots.map((slot) => slot.kind === "exit");
    const layout: AnonymousLayout = {
      key: entry ? { kind: "entry" } : { kind: "commitment", class: vector.class },
      inputs: vector.inputs.length,
      outputs: vector.slots.length,
      exits,
    };
    const disclosure: RingDisclosure = {
      kind: "anonymous",
      layout,
      seedOut: exits ? seedOut : undefined,
      senderKey: field(vector.sender_key),
      outputs: vector.slots.map(outputOpening),
      inputs: entry
        ? {
            kind: "openings",
            senderNullifierPk: field(vector.sender_nullifier_pk),
            inputs: vector.inputs.map((input) => ({
              asset: field(input.asset),
              amount: BigInt(input.amount),
              blinding: field(input.blinding),
            })),
          }
        : { kind: "commitments", hashes: vector.inputs.map((input) => field(input.commitment)) },
    };
    const published = vector.published.map(field);

    it("names exactly the flags its key and slots need", () => {
      expect(exits).toBe(slotExits.includes(true));
      expect((vector.layout & 8) !== 0).toBe(entry);
      expect((vector.layout & 2) !== 0).toBe(false);
      expect(vector.class).toBe(entry ? 8 : 4);
    });

    it("derives the seed every exit and dummy blinding comes from", () => {
      expect(outputBlindingSeed(firstNullifier, field(vector.blinding_seed))).toEqual(seedOut);
    });

    it("seals the slots and the spent inputs to the published fields and opens them back", () => {
      expect(sealRingDisclosure(key, disclosure)).toEqual(published);
      expect(
        openRingDisclosure(key, {
          layout: { kind: "anonymous", ...layout },
          fields: published,
          exits: slotExits,
        }),
      ).toEqual(disclosure);
    });

    it("pads each plaintext field with the CROD pad at its position", () => {
      const pad = { key: key.txViewingSecret, salt: key.salt, domain: RingDomain.disclosurePad };
      expect(unmaskDisclosure({ ...pad, fields: published })).toEqual(vector.plaintext.map(field));
      expect(maskDisclosure({ ...pad, fields: vector.plaintext.map(() => ZERO) })).toEqual(
        vector.pad.map(field),
      );
      expect(hashChain4(published)).toEqual(field(vector.disclosure_chain));
    });

    it("rebuilds every slot's stream tag, ring secret, blinding, body and commitment", () => {
      const txKey = ViewingKey.fromBytes(key.txViewingSecret);
      const epoch = BigInt(vector.epoch);
      vector.slots.forEach((slot, outputIndex) => {
        const treeId = vector.output_tree_id;
        if (slot.kind !== "ring") {
          const blinding = transactOutputBlinding(firstNullifier, seedOut, outputIndex);
          expect(blinding).toEqual(field(slot.blinding));
          expect(
            slot.kind === "dummy"
              ? dummyUtxoHash(treeId, blinding)
              : commitment(slot, treeId, ZERO),
          ).toEqual(field(slot.output_hash));
          return;
        }
        const recipient = X25519PublicKey.fromU(field(need(slot.recipient_u, "recipient_u")));
        const tag = hex<Bytes31>(need(slot.tag, "tag"), 31);
        const index = tagIndex("index" in slot ? need(slot.index, "index") : 0);
        if (slot.stream === "inbox") {
          const inbox = inboxKey(ringId, recipient);
          expect(inbox).toEqual(
            field(need("inbox_key" in slot ? slot.inbox_key : undefined, "inbox_key")),
          );
          expect(inboxTag(inbox, epoch, index)).toEqual(tag);
        } else if (slot.stream === "pair") {
          const pair = pairKey(
            field(
              need(
                "first_contact_secret" in slot ? slot.first_contact_secret : undefined,
                "first_contact_secret",
              ),
            ),
          );
          expect(pair).toEqual(
            field(need("pair_key" in slot ? slot.pair_key : undefined, "pair_key")),
          );
          expect(pairTag(pair, epoch, index)).toEqual(tag);
        } else {
          expect(
            ringTag(field(need("tag_field" in slot ? slot.tag_field : undefined, "tag_field"))),
          ).toEqual(tag);
        }
        expect(field(slot.owner_tag)).toEqual(Uint8Array.of(0, ...tag));
        const slotSecret = deliveredSlotSecret({
          agreement: txKey.ecdh(recipient),
          txViewingKey: txKey.publicKey(),
          recipientViewingKey: recipient,
          salt: key.salt,
          outputIndex,
          firstNullifier,
        });
        expect(slotSecret).toEqual(field(need(slot.slot_secret, "slot_secret")));
        const ringSecret = anonymousRingSecret(slotSecret, tag);
        expect(ringSecret).toEqual(field(need(slot.ring_secret, "ring_secret")));
        expect(ringOutputBlinding({ firstNullifier, ringSecret, outputIndex })).toEqual(
          field(slot.blinding),
        );
        expect(
          sealDeliveredBody(slotSecret, {
            assetAddress: field(need(slot.asset_address, "asset_address")),
            amount: BigInt(need(slot.amount, "amount")),
          }),
        ).toEqual(hex(need(slot.body, "body"), 40));
        expect(commitment(slot, treeId, ringId)).toEqual(field(slot.output_hash));
      });
      txKey.destroy();
    });

    it("rebuilds every spent input's owner and commitment, ring id zero on a default-ring note", () => {
      const owner = ownerHash(
        solanaOwnerIdentity(field(vector.sender_key)),
        field(vector.sender_nullifier_pk),
      ) as Bytes32;
      for (const input of vector.inputs) {
        expect(owner).toEqual(field(input.owner_hash));
        expect(
          fieldUtxoHash({
            owner,
            assetField: field(input.asset),
            amount: BigInt(input.amount),
            blinding: field(input.blinding),
            treeId: input.input_tree_id,
            dataHash: ZERO,
            ringDataHash: ZERO,
            ringId: input.ring === "ring" ? ringId : ZERO,
          }),
        ).toEqual(field(input.commitment));
      }
    });
  },
);

function outputOpening(slot: VectorSlot): AnonymousOutputOpening {
  if (slot.kind === "dummy") return { kind: "dummy" };
  const nullifierPk = field(need(slot.nullifier_pk, "nullifier_pk"));
  return slot.kind === "exit"
    ? {
        kind: "exit",
        nullifierPk,
        asset: field(need(slot.asset, "asset")),
        amount: BigInt(need(slot.amount, "amount")),
      }
    : {
        kind: "ring",
        nullifierPk,
        ownerKey: field(need(slot.owner_key, "owner_key")),
        recipientU: field(need(slot.recipient_u, "recipient_u")),
      };
}

/** The SPP UTXO hash of an opened slot, `ringId` zero on an exit. */
function commitment(slot: VectorSlot, treeId: number, ringId: Bytes32): Bytes32 {
  return fieldUtxoHash({
    owner: ownerHash(
      solanaOwnerIdentity(field(need(slot.owner_key, "owner_key"))),
      field(need(slot.nullifier_pk, "nullifier_pk")),
    ) as Bytes32,
    assetField: field(need(slot.asset, "asset")),
    amount: BigInt(need(slot.amount, "amount")),
    blinding: field(slot.blinding),
    treeId,
    dataHash: field(need(slot.data_hash, "data_hash")),
    ringDataHash: field(need(slot.ring_data_hash, "ring_data_hash")),
    ringId,
  });
}
