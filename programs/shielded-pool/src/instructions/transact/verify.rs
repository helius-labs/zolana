pub const MAX_INPUTS: usize = 60;

/// Fixed width of the circuit's signer fold: the payer plus one slot per
/// input. Sizes the zero-suffix table, not the program's signer array.
pub const MAX_SIGNERS: usize = MAX_INPUTS + 1;

/// Distinct owner-signer identities the program will hash, payer included.
/// Deliberately independent of the input count: the fold width is what the
/// circuit fixes, while the number of *distinct* signers a real transaction
/// carries is small. Transaction v1 caps signatures at 12, so this is not the
/// binding limit today, and `account.rs` separately rejects a signer run longer
/// than the input count.
pub const MAX_UNIQUE_SIGNERS: usize = 8;

/// Owner-hash memo capacity. Deliberately small and independent of the shape
/// constants: `ArrayMap` is a linear scan, so a large cache is quadratic over
/// the outputs, and the only reliable hits are outputs owned by a signer.
/// Overflowing it costs a rehash, never a failed transaction.
const MAX_OWNER_HASHES: usize = 8;

pub type OwnerHashCache = ArrayMap<[u8; 32], [u8; 32], MAX_OWNER_HASHES>;

const ASSIGNED_OUTPUT_OWNERS: u8 = 1 << 0;
const ASSIGNED_OWNER_SIGNERS: u8 = 1 << 1;
const ASSIGNED_PUBLIC_TRANSFERS: u8 = 1 << 2;
const ASSIGNED_INPUT_TREE: u8 = 1 << 3;
const ASSIGNED_EXTERNAL_DATA: u8 = 1 << 4;
const ASSIGNED_RING_PROGRAM: u8 = 1 << 5;
const ALL_ASSIGNMENTS: u8 = ASSIGNED_OUTPUT_OWNERS
    | ASSIGNED_OWNER_SIGNERS
    | ASSIGNED_PUBLIC_TRANSFERS
    | ASSIGNED_INPUT_TREE
    | ASSIGNED_EXTERNAL_DATA
    | ASSIGNED_RING_PROGRAM;

#[derive(Debug)]
pub struct TransactProofInputs {
    /// Left-folded chains over the per-input roots, in `ix.inputs` order.
    /// `input_count` is how many were folded; `public_input_hash` requires it
    /// to equal the circuit's input count, which is the check the old
    /// fixed-width arrays performed by slicing.
    pub utxo_root_chain: [u8; 32],
    pub nullifier_tree_root_chain: [u8; 32],
    pub input_count: u8,
    pub signer_pk_hashes: [[u8; 32]; MAX_UNIQUE_SIGNERS],
    /// Left-folded chain over the per-output owner hashes, in `ix.outputs`
    /// order. In `ConfidentialMarked` mode an unmarked output folds an explicit
    /// zero, reproducing the zero-filled slot of the array this replaced.
    /// `OutputOwnerMode::None` folds nothing and leaves the count at zero,
    /// because the public input omits the field entirely.
    pub output_owner_chain: [u8; 32],
    pub output_owner_count: u8,
    pub external_data_hash: [u8; 32],
    pub public_slot_assets: [[u8; 32]; N_PUBLIC_SLOTS],
    pub public_slot_amounts: [i128; N_PUBLIC_SLOTS],
    pub ring_program_id: [u8; 32],
    pub allow_dummy_inputs: [u8; 32],
    /// Number of unique entries at the head of `signer_pk_hashes` (payer
    /// first); the remaining slots are zero padding. Public only so the moved
    /// circuit-vector tests can pin the assembly; production code writes it
    /// exclusively through `fill_owner_signer_hashes`.
    pub unique_owner_signer_count: u8,
    assignments: u8,
}

impl TransactProofInputs {
    pub fn new(circuit: CircuitId) -> Self {
        let mut assignments = 0;
        if matches!(circuit, CircuitId::ConfidentialEddsa(..)) {
            assignments |= ASSIGNED_RING_PROGRAM;
        }
        Self {
            utxo_root_chain: [0u8; 32],
            nullifier_tree_root_chain: [0u8; 32],
            input_count: 0,
            signer_pk_hashes: [[0u8; 32]; MAX_UNIQUE_SIGNERS],
            output_owner_chain: [0u8; 32],
            output_owner_count: 0,
            external_data_hash: [0u8; 32],
            public_slot_assets: [[0u8; 32]; N_PUBLIC_SLOTS],
            public_slot_amounts: [0i128; N_PUBLIC_SLOTS],
            ring_program_id: [0u8; 32],
            allow_dummy_inputs: [0u8; 32],
            unique_owner_signer_count: 0,
            assignments,
        }
    }

    pub(crate) fn assign_ring_program_id(&mut self, ring_program_id: [u8; 32]) {
        self.ring_program_id = ring_program_id;
        self.assignments |= ASSIGNED_RING_PROGRAM;
    }

    pub(crate) fn assign_input_tree(
        &mut self,
        utxo_root_chain: [u8; 32],
        nullifier_tree_root_chain: [u8; 32],
        input_count: usize,
        allow_dummy_inputs: [u8; 32],
    ) -> Result<(), ProgramError> {
        self.utxo_root_chain = utxo_root_chain;
        self.nullifier_tree_root_chain = nullifier_tree_root_chain;
        self.input_count =
            u8::try_from(input_count).map_err(|_| ShieldedPoolError::InvalidTransactShape)?;
        self.allow_dummy_inputs = allow_dummy_inputs;
        self.assignments |= ASSIGNED_INPUT_TREE;
        Ok(())
    }

    pub(crate) fn assign_external_data_hash(&mut self, external_data_hash: [u8; 32]) {
        self.external_data_hash = external_data_hash;
        self.assignments |= ASSIGNED_EXTERNAL_DATA;
    }

    pub fn ensure_complete(&self) -> Result<(), ProgramError> {
        if self.assignments != ALL_ASSIGNMENTS {
            return Err(ShieldedPoolError::InvalidTransactShape.into());
        }
        Ok(())
    }

    // Assign the payer and ordered, first-occurrence-deduplicated EdDSA signer
    // identities. The payer occupies slot zero and seeds `seen`, so an appended
    // payer is ignored.
    #[profile]
    pub fn fill_owner_signer_hashes(
        &mut self,
        payer: &AccountView,
        owner_signers: &[AccountView],
        owner_hashes: &mut OwnerHashCache,
    ) -> Result<(), ProgramError> {
        let payer_address = payer.address().to_bytes();
        self.signer_pk_hashes[0] = cached_owner_hash(owner_hashes, &payer_address)?;

        let mut seen: ArrayMap<[u8; 32], (), MAX_UNIQUE_SIGNERS> = ArrayMap::new();
        seen.insert(payer_address, (), ShieldedPoolError::InvalidTransactShape)?;
        let mut unique_count = 1usize;
        for signer in owner_signers {
            let address = signer.address().to_bytes();
            if seen.get_by_pubkey(&address).is_some() {
                continue;
            }
            seen.insert(address, (), ShieldedPoolError::InvalidTransactShape)?;
            *self
                .signer_pk_hashes
                .get_mut(unique_count)
                .ok_or(ShieldedPoolError::InvalidTransactShape)? =
                cached_owner_hash(owner_hashes, &address)?;
            unique_count += 1;
        }
        self.unique_owner_signer_count =
            u8::try_from(unique_count).map_err(|_| ShieldedPoolError::InvalidTransactShape)?;
        self.assignments |= ASSIGNED_OWNER_SIGNERS;
        Ok(())
    }

    #[profile]
    pub fn fill_output_owner_chain(
        &mut self,
        mode: OutputOwnerMode,
        resolved_outputs: &[ResolvedOutput],
        owner_hashes: &mut OwnerHashCache,
    ) -> Result<(), ProgramError> {
        let mut chain = HashChain::new();
        match mode {
            OutputOwnerMode::None => {}
            OutputOwnerMode::All => {
                for output in resolved_outputs.iter() {
                    chain.push(&cached_owner_hash(owner_hashes, &output.owner_tag)?)?;
                }
            }
            OutputOwnerMode::ConfidentialMarked => {
                for output in resolved_outputs.iter() {
                    let element = if output.data.is_some_and(is_confidential_encrypted_output) {
                        cached_owner_hash(owner_hashes, &output.owner_tag)?
                    } else {
                        [0u8; 32]
                    };
                    chain.push(&element)?;
                }
            }
        }
        if mode != OutputOwnerMode::None {
            self.output_owner_chain = chain.finish();
            self.output_owner_count = u8::try_from(resolved_outputs.len())
                .map_err(|_| ShieldedPoolError::InvalidTransactShape)?;
        }
        self.assignments |= ASSIGNED_OUTPUT_OWNERS;
        Ok(())
    }

    pub fn assign_public_amounts_and_assets(
        &mut self,
        interface_transfers: &[InterfaceTransfer],
        settlements: &[Settlement<'_>],
        num_public_asset_slots: usize,
    ) -> Result<(), ProgramError> {
        if interface_transfers.len() != settlements.len() || num_public_asset_slots > N_PUBLIC_SLOTS
        {
            return Err(ShieldedPoolError::InvalidTransactShape.into());
        }

        let mut used_slots = 0usize;
        for (transfer, settlement) in interface_transfers.iter().zip(settlements.iter()) {
            let amount = signed_amount(*transfer);
            if amount == 0 || transfer.is_deposit() != settlement.is_deposit() {
                return Err(ShieldedPoolError::InvalidSettlementAccounts.into());
            }

            let hashed_mint = match settlement.spl_asset()? {
                Some(mint) => hash_bytes(&mint)?,
                None => SOL_ASSET_FIELD,
            };
            match self.public_slot_assets[..used_slots]
                .iter()
                .position(|slot_asset| *slot_asset == hashed_mint)
            {
                Some(index) => {
                    let net = self.public_slot_amounts[index]
                        .checked_add(amount)
                        .ok_or(ShieldedPoolError::PublicAssetAmountOverflow)?;
                    self.public_slot_amounts[index] = checked_slot_amount(net)?;
                }
                None => {
                    if used_slots == num_public_asset_slots {
                        return Err(ShieldedPoolError::TooManyPublicAssets.into());
                    }
                    self.public_slot_assets[used_slots] = hashed_mint;
                    self.public_slot_amounts[used_slots] = checked_slot_amount(amount)?;
                    used_slots += 1;
                }
            }
        }
        if self.public_slot_amounts[..used_slots].contains(&0) {
            return Err(ShieldedPoolError::ZeroNetInterfaceTransferAmount.into());
        }
        self.assignments |= ASSIGNED_PUBLIC_TRANSFERS;
        Ok(())
    }
}

fn cached_owner_hash(
    owner_hashes: &mut OwnerHashCache,
    owner_tag: &[u8; 32],
) -> Result<[u8; 32], ProgramError> {
    if let Some(hash) = owner_hashes.get_by_pubkey(owner_tag) {
        return Ok(*hash);
    }
    let hash = hash_bytes(owner_tag)?;
    // A full cache is a miss, not an error: the memo is a compute optimization,
    // so exhausting it must degrade to rehashing rather than reject an
    // otherwise valid transaction. `ArrayMap` has no `try_insert`, hence the
    // explicit capacity check.
    if owner_hashes.len() < MAX_OWNER_HASHES {
        owner_hashes.insert(
            *owner_tag,
            hash,
            ProgramError::from(ShieldedPoolError::InvalidTransactShape),
        )?;
    }
    Ok(hash)
}

fn checked_slot_amount(net: i128) -> Result<i128, ProgramError> {
    if u64::try_from(net.unsigned_abs()).is_err() {
        return Err(ShieldedPoolError::PublicAssetAmountOverflow.into());
    }
    Ok(net)
}

fn signed_amount(transfer: InterfaceTransfer) -> i128 {
    let amount = i128::from(transfer.amount());
    if transfer.is_deposit() {
        amount
    } else {
        -amount
    }
}

pub struct TransactProof<'a> {
    ix: &'a TransactIxDataRef<'a>,
    // Borrowed, not owned: holding it by value would copy the struct onto this
    // frame on top of the owner's copy, for no benefit. Its size no longer
    // scales with the input or output count, but the copy would still be dead
    // weight in the verifier's frame.
    derived: &'a TransactProofInputs,
}

impl<'a> TransactProof<'a> {
    pub fn new(ix: &'a TransactIxDataRef<'a>, derived: &'a TransactProofInputs) -> Self {
        Self { ix, derived }
    }

    /// The processor validates the selector against the dispatched instruction
    /// before account parsing. The validated selector is then the source of truth
    /// for the public-input layout and verifying key.
    #[inline(never)]
    pub fn verify(&self) -> ProgramResult {
        let public_input_hash = self.public_input_hash()?;
        let verifying_key = self
            .ix
            .tail
            .circuit
            .verifying_key()
            .ok_or(ShieldedPoolError::InvalidTransactShape)?;
        let encoding_err = ShieldedPoolError::InvalidTransactProofEncoding;
        let verify_err = ShieldedPoolError::TransactProofVerificationFailed;
        let proof_data = &self.ix.tail.proof;
        let commitment = self
            .ix
            .tail
            .circuit
            .bsb22_commitment()
            .map(|value| (&value.commitment, &value.commitment_pok));
        let proof = verifier::CompressedGroth16Proof {
            a: &proof_data.a,
            b: &proof_data.b,
            c: &proof_data.c,
            commitment,
        };
        verifier::verify_groth16(
            proof,
            public_input_hash,
            verifying_key,
            encoding_err,
            verify_err,
        )
    }

    fn n_inputs(&self) -> usize {
        usize::from(self.ix.tail.circuit.num_inputs())
    }

    fn n_outputs(&self) -> usize {
        usize::from(self.ix.tail.circuit.num_outputs())
    }

    fn n_public_asset_slots(&self) -> usize {
        usize::from(self.ix.tail.circuit.num_public_asset_slots())
    }

    #[inline(never)]
    pub fn public_input_hash(&self) -> Result<[u8; 32], ProgramError> {
        let n_in = self.n_inputs();
        let n_out = self.n_outputs();
        let n_public_asset_slots = self.n_public_asset_slots();
        let shape = ShieldedPoolError::InvalidTransactShape;
        // The root chains were folded over `ix.inputs`; requiring the folded
        // count to equal the circuit's input count replaces the bounds check
        // that slicing the old fixed-width arrays performed.
        if usize::from(self.derived.input_count) != n_in {
            return Err(shape.into());
        }
        let signer_width = if self.ix.tail.circuit.requires_input_signatures() {
            n_in.checked_add(1).ok_or(shape)?
        } else {
            1
        };
        // `signer_width` is the circuit's fixed fold width, `n_in + 1`, which
        // reaches 61 at the largest shape. It is NOT a bound on this array:
        // `signer_pk_hashes` holds only the accepted unique signers, at most
        // `MAX_UNIQUE_SIGNERS`, and `fixed_signer_hash_chain` covers the zero
        // tail from the suffix table. Slicing the array by the fold width
        // rejects every shape with more than `MAX_UNIQUE_SIGNERS - 1` inputs.
        let unique_signer_pk_hashes = self
            .derived
            .signer_pk_hashes
            .get(..usize::from(self.derived.unique_owner_signer_count))
            .ok_or(shape)?;
        let public_slot_assets = self
            .derived
            .public_slot_assets
            .get(..n_public_asset_slots)
            .ok_or(shape)?;
        let public_slot_amounts = self
            .derived
            .public_slot_amounts
            .get(..n_public_asset_slots)
            .ok_or(shape)?;

        // Folded straight off the instruction data: `validate_circuit_type`
        // already pinned both counts to the circuit's shape, so the scratch
        // buffers these replaced could never overflow, and folding keeps the
        // frame independent of the input and output counts.
        let nullifier_chain = create_hash_chain(
            self.ix
                .tail
                .inputs
                .iter()
                .map(|input| &input.nullifier_hash),
        )?;
        let output_chain =
            create_hash_chain(self.ix.bound.outputs.iter().map(|output| output.utxo_hash))?;
        let mut fields: ArrayVec<[[u8; 32]; 20]> = ArrayVec::new();
        fields.extend_from_slice(&[
            nullifier_chain,
            output_chain,
            self.derived.utxo_root_chain,
            self.derived.nullifier_tree_root_chain,
            *self.ix.tail.private_tx_hash,
        ]);
        if self.ix.tail.circuit.is_p256() {
            let message_digest = Sha256::hash(self.ix.tail.private_tx_hash).map_err(caused_by(
                ShieldedPoolError::TransactProofVerificationFailed,
            ))?;
            fields.push(hash_bytes(&message_digest)?);
            fields.push(match self.ix.tail.circuit.default_p256_owner_tag() {
                Some(owner_tag) => hash_bytes(owner_tag)?,
                None => [0u8; 32],
            });
        }
        fields.push(self.derived.external_data_hash);
        for (asset, amount) in public_slot_assets.iter().zip(public_slot_amounts.iter()) {
            fields.push(*asset);
            fields.push(amount_field(*amount)?);
        }
        fields.extend_from_slice(&[
            self.derived.ring_program_id,
            fixed_signer_hash_chain(unique_signer_pk_hashes, signer_width)?,
            self.derived.allow_dummy_inputs,
        ]);
        if self.ix.tail.circuit.output_owner_mode() != OutputOwnerMode::None {
            // Same bounds role as the input-count check above: the chain must
            // cover exactly the circuit's output count.
            if usize::from(self.derived.output_owner_count) != n_out {
                return Err(shape.into());
            }
            fields.push(self.derived.output_owner_chain);
        }
        create_hash_chain_from_slice(fields.as_slice()).map_err(Into::into)
    }
}

