//! One R1CS digest per DSL operation at a representative size. The size pins
//! next to each operation catch a changed row count; these also catch a changed
//! coefficient. A changed digest means the operation's constraints changed,
//! which changes every proving key built on it: re-derive and re-pin
//! deliberately.

